static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }

/* asm: DrawDungeonView @0447 */
void DrawDungeonView(u16 bx, u8 al, u8 ah)
{
    /* pushf / push ax / push es: saved and restored (the flags too) */
    ViewPos[0] = bx & 0xFF;                     /* mov word ptr ViewPos, bx: x low, y high */
    ViewPos[1] = bx >> 8;
    ViewFacing = al;
    ViewLevel = ah;
    /* mov es, 0B800h: ES = CgaMem for the drawing routines */
    i8 r = DrawSlot(0);                         /* own cell */
    if (r == 0) goto DrawView_Left0;            /* je: open: look around */
    if (r >= 0) goto DrawView_Ahead1;           /* jns: standing in a door: only straight ahead */
    goto DrawView_Done;                         /* in a wall (or secret door): nothing more */

/* to the left: the wall beside you, then the cells diagonally to the left */
DrawView_Left0:
    if (DrawSlot(1) < 0) goto DrawView_Right0;          /* js */
    if (DrawSlot(3) < 0) goto DrawView_Right0;
    if (DrawSlot(6) < 0) goto DrawView_Right0;
    if (DrawSlot(0x0A) < 0) goto DrawView_Right0;
    if (DrawSlot(0x0F) < 0) goto DrawView_Right0;
    DrawSlot(0x15);
/* to the right, the same */
DrawView_Right0:
    if (DrawSlot(2) < 0) goto DrawView_Ahead1;
    if (DrawSlot(5) < 0) goto DrawView_Ahead1;
    if (DrawSlot(9) < 0) goto DrawView_Ahead1;
    if (DrawSlot(0x0E) < 0) goto DrawView_Ahead1;
    if (DrawSlot(0x14) < 0) goto DrawView_Ahead1;
    DrawSlot(0x1B);
/* one cell ahead; if it is open, the lines of sight to its left and right */
DrawView_Ahead1:
    if (DrawSlot(4) != 0) goto DrawView_Done;           /* jne: a wall or door ahead ends the view */
    if (DrawSlot(7) < 0) goto DrawView_Right1;
    if (DrawSlot(0x0B) < 0) goto DrawView_Right1;
    if (DrawSlot(0x10) < 0) goto DrawView_Right1;
    DrawSlot(0x16);
DrawView_Right1:
    if (DrawSlot(8) < 0) goto DrawView_Ahead2;
    if (DrawSlot(0x0D) < 0) goto DrawView_Ahead2;
    if (DrawSlot(0x13) < 0) goto DrawView_Ahead2;
    DrawSlot(0x1A);
/* two cells ahead, the same */
DrawView_Ahead2:
    if (DrawSlot(0x0C) != 0) goto DrawView_Done;
    if (DrawSlot(0x11) < 0) goto DrawView_Right2;
    if (DrawSlot(0x17) < 0) goto DrawView_Right2;
    DrawSlot(0x1C);
DrawView_Right2:
    if (DrawSlot(0x12) < 0) goto DrawView_Ahead3;
    if (DrawSlot(0x19) < 0) goto DrawView_Ahead3;
    DrawSlot(0x1F);
/* three cells ahead (the farthest): if open, only the walls beside it */
DrawView_Ahead3:
    if (DrawSlot(0x18) < 0) goto DrawView_Done;
    DrawSlot(0x1D);
    DrawSlot(0x1E);
DrawView_Done:
    return;                                     /* pop es / pop ax / popf */
}

/* asm: DrawSlot @0533
 * The result is only in the flags (or al,al before the final `pop ax`, which gives AL back as the
 * slot): ZF set = 0, SF set = -1 (FFh), neither = 1. The header's "AL" is the value that set them. */
i8 DrawSlot(u8 al)
{
    u8 dl = SlotDXTbl[al];                      /* bl = al, bh = 0 */
    u8 dh = SlotDYTbl[al];
    u8 ah = ViewFacing;
    if (ah != 0) {
        do {                                    /* DrawSlot_Turn: a quarter right: (dx,dy) -> (-dy,dx) */
            u8 t = dl; dl = dh; dh = t;         /* xchg dl, dh */
            dl = (u8)(0 - dl);                  /* neg dl */
            ah--;
        } while (ah != 0);
    }
    ah = al;                                    /* DrawSlot_Cell: AH = slot */
    u8 bl = ViewPos[0] + dl;                    /* mov bx, ViewPos / add bl, dl / add bh, dh */
    u8 bh = ViewPos[1] + dh;
    bl &= 0x0F;                                 /* and bx, 0F0Fh: the map wraps around */
    bh &= 0x0F;
    const u8 *cellp;
    u8 cell = GetCell(bl, bh, &cellp);          /* AL = the cell */
    if (cell & 0x80) {                          /* js DrawSlot_Wall: 80-FF */
        if (cell >= 0xC0) {                     /* DrawSlot_Door: C0-FF */
            DrawFace(ah);                       /* the wall... */
            ah += 0x20;
            DrawFace(ah);                       /* ...and the door in it (slot 0: the opening is erased) */
            if (ah == 0x20) return 1;           /* DrawSlot_InDoor: AL = 1, neither flag */
            return -1;                          /* AL = 0FFh: SF set */
        }
        DrawFace(ah);                           /* 80-BF (wall, secret door A0): the plain wall */
        return -1;
    }
    dl = cell;
    if (dl & 0x10)                              /* ladder up? */
        DrawLadder(ah, 0);
    if (dl & 0x20)                              /* ladder down? */
        DrawLadder(ah, 1);
    if (dl & 0x40)                              /* chest? */
        DrawChest(ah);
    return 0;                                   /* DrawSlot_Open: AL = 0, ZF set */
}

/* asm: DrawFace @05B5 */
void DrawFace(u8 ah)
{
    const u8 *di = &FaceTbl[ah * 8];            /* entry AH * 8 */
    u8 cl = di[0];                              /* x */
    u8 ch = di[1];                              /* top y */
    u8 dl = di[2];                              /* bottom y */
    u8 al = di[3];                              /* x step */
    u8 topReload = di[4], topCount = topReload; /* SI = top slope: BL reload, BH countdown */
    u8 botReload = di[5], botCount = botReload; /* BP = bottom slope, the same */
    u16 lines = di[6];                          /* DI = lines */
    if (ViewFacing & 1)                         /* east or west? */
        cl++;                                   /* every line one pixel to the right */
    for (;;) {                                  /* DrawFace_Loop */
        DrawVLine(cl, ch, dl, ah);              /* AH is still the entry: 20h erases */
        lines--;
        if (lines == 0) break;
        cl += al;
        topCount--;                             /* first pixel: top, bottom */
        if (topCount == 0) { topCount = topReload; ch++; }
        botCount--;
        if (botCount == 0) { botCount = botReload; dl--; }
        if (al == 1) continue;                  /* a step of 1 pixel: done (no entry has one) */
        topCount--;                             /* second pixel: top, bottom again */
        if (topCount == 0) { topCount = topReload; ch++; }
        botCount--;
        if (botCount == 0) { botCount = botReload; dl--; }
    }
}

/* asm: DrawLadder @063B */
void DrawLadder(u8 ah, u8 al)
{
    if (ah >= 0x15) return;                     /* nothing for slots 21-31 (too far) */
    const u8 *si = &LadderTbl[ah * 8];
    u8 cl = si[0];                              /* left rail x */
    u8 dl = cl;
    u8 ch, dh;
    if (cl & 0x80) return;                      /* x >= 80h: no ladder (no entry has one) */
    ch = si[2];
    if (ch != 0) {                              /* else the left rail is hidden */
        if (al != 0)
            ch = 0x7F - si[2];                  /* down: mirror to the floor */
        ah = ch;                                /* AH is the scratch copy of the y from here on */
        dh = 0x40;                              /* to the horizon */
        DrawLine(cl, ch, dl, dh);
        cl++;                                   /* and again one pixel to the right */
        dl++;
        ch = ah;
        DrawLine(cl, ch, dl, dh);
    }
    cl = si[1];                                 /* DrawLadder_Right: right rail x */
    dl = cl;
    ch = si[3];
    if (ch != 0) {                              /* else the right rail is hidden */
        if (al != 0)
            ch = 0x7F - si[3];
        ah = ch;
        dh = 0x40;
        DrawLine(cl, ch, dl, dh);
        cl--;
        dl--;
        ch = ah;
        DrawLine(cl, ch, dl, dh);
    }
    cl = si[0];                                 /* DrawLadder_Rungs: from the left rail... */
    dl = si[1];                                 /* ...to the right rail */
    ch = si[4];
    if (al != 0)
        ch = 0x7F - si[4];
    dh = ch;
    DrawLine(cl, ch, dl, dh);
    cl = si[0];
    ch = si[5];
    if (al != 0)
        ch = 0x7F - si[5];
    dh = ch;
    DrawLine(cl, ch, dl, dh);
}

/* asm: DrawLine @06D5 */
void DrawLine(u8 cl, u8 ch, u8 dl, u8 dh)
{
    /* Bresenham. BP = |dx| (low), |dy| (high); SI = x step (low), y step (high), +1 or -1. */
    u8 adx, ady, sx, sy;
    adx = dl - cl;
    if (dl >= cl) {                             /* jae DrawLine_Right */
        sx = 1;
    } else {
        adx = (u8)(0 - adx);                    /* neg bl */
        sx = 0xFF;
    }
    ady = dh - ch;
    if (dh >= ch) {                             /* jae DrawLine_Down */
        sy = 1;
    } else {
        ady = (u8)(0 - ady);
        sy = 0xFF;
    }
    if (adx >= ady) {                           /* cmp bl, bh / jb DrawLine_Steep */
        u16 di = adx;                           /* |dx| points, one per x */
        u8 ah = adx >> 1;                       /* AH = error, starts at |dx|/2 */
        do {                                    /* DrawLine_XLoop */
            ah += ady;
            u8 al = ah - adx;
            if (ah >= adx) {                    /* no borrow */
                ah = al;
                ch += sy;
            }
            cl += sx;                           /* DrawLine_XStep */
            PlotPixel(cl, ch);
            di--;                               /* equal points: DI = 0 would loop 65536 times */
        } while (di != 0);
    } else {                                    /* DrawLine_Steep */
        u16 di = ady;                           /* |dy| points, one per y */
        u8 ah = ady >> 1;
        do {                                    /* DrawLine_YLoop */
            ah += adx;
            u8 al = ah - ady;
            if (ah >= ady) {
                ah = al;
                cl += sx;
            }
            ch += sy;                           /* DrawLine_YStep */
            PlotPixel(cl, ch);
            di--;
        } while (di != 0);
    }
}


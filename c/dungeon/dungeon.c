{
    if (ah >= 0x15) return;                     /* nothing for slots 21-31 */
    const u8 *bx = &ChestTbl[ah * 4];
    u8 cl = bx[0];                              /* left x */
    if (cl & 0x80) return;                      /* x >= 80h: none (no entry has one) */
    u8 dh = bx[1];                              /* right x */
    u8 ch = bx[2];                              /* top y */
    u8 dl = bx[3];                              /* bottom y */
    do {                                        /* DrawChest_Loop */
        DrawVLine(cl, ch, dl, ah);
        cl++;
    } while (cl < dh);
}

/* asm: DrawVLine @0789 */
void DrawVLine(u8 cl, u8 ch, u8 dl, u8 ah)
{
    if (ah != 0x20) {
        cl += 0x20;                             /* screen x */
        u16 dx = (u8)(dl - ch);                 /* DX = lines (0 would draw 65536 lines, never asked) */
        u16 di = cl >> 2;                       /* DI = byte in the line (4 pixels a byte) */
        u8 al = 0xC0;                           /* pixel value 3 (white)... */
        al >>= (cl & 3) * 2;                    /* ...moved to the pixel's two bits */
        const u8 *si = ScreenRowTbl + (u16)(ch * 2) + 0x40;     /* screen line = y + 20h */
        do {                                    /* DrawVLine_Set */
            u16 bx = Rd(si);
            si += 2;
            CgaMem[(u16)(bx + di)] |= al;
            dx--;
        } while (dx != 0);
    } else {                                    /* DrawVLine_Erase: the door around you */
        cl += 0x20;
        u16 dx = (u8)(dl - ch);
        u16 di = cl >> 2;
        u8 al = 0x3F;                           /* mask clearing the pixel's two bits */
        u8 n = (cl & 3) * 2;
        al = (u8)((al >> n) | (al << (8 - n)));     /* ror al, cl */
        const u8 *si = ScreenRowTbl + (u16)(ch * 2) + 0x40;
        do {                                    /* DrawVLine_Clear */
            u16 bx = Rd(si);
            si += 2;
            CgaMem[(u16)(bx + di)] &= al;
            dx--;
        } while (dx != 0);
    }
}

/* asm: PlotPixel @0805 */
void PlotPixel(u8 cl, u8 ch)
{
    ch += 0x20;                                 /* screen line */
    cl += 0x20;                                 /* screen x */
    u8 al = cl >> 2;
    u8 ah = 0xC0;
    ah >>= (cl & 3) * 2;
    u16 bx = Rd(ScreenRowTbl + (u16)(ch * 2));  /* bl = ch, bh = 0 / shl bx, 1 / ROWTAB[bx] */
    bx += al;                                   /* add bl, al / adc bh, 0 */
    CgaMem[bx] |= ah;
}

/* asm: GetCell @0833 */
u8 GetCell(u8 bl, u8 bh, const u8 **bx)
{
    bh <<= 4;                                   /* shl bh, 1 x4 */
    bl += bh;                                   /* y*16 + x */
    *bx = DungeonMap + (((u16)ViewLevel << 8) | bl);        /* mov bh, ViewLevel / lea bx, DMAP[bx]: + level*256 */
    return **bx;                                /* AL = the cell */
}

/* dungeon.c: DUNGEON.ASM, DUNGEON.DAT: the 3D dungeon view, a code overlay EXODUS loads at 0100
 * (0100-084A). 0103-0106 hold what it is given, 0107-0446 are byte tables, the code starts at 0447.
 *
 * EXODUS (DUNEVENT) clears the view and, when a light is lit, calls 0100 with BX = party x,y,
 * AL = facing (0 north, 1 east, 2 south, 3 west), AH = level. DrawDungeonView looks at up to 32
 * "view slots": cells at fixed offsets around the party (SlotDXTbl/SlotDYTbl, written for facing
 * north and rotated by DrawSlot), up to 3 cells ahead and 3 to each side, near to far, and draws
 * each cell's wall face, door, ladders and chest. It stops a line of sight at the first wall, so
 * nothing hidden is drawn (there is no other clipping).
 * Drawing: everything is white (pixel value 3) ORed into CGA memory (ES = B800, CgaMem). The view
 * has its own coordinates: x 00-80h, y 00-7Fh, horizon and centre at 40h; screen pixel = view + 20h
 * (the 11x11 map window). A wall face is a set of vertical lines every second pixel (DrawFace); a
 * door fills the gaps between the stripes; ladders are lines (DrawLine), a chest a filled box
 * (DrawChest). The perspective is not exact: each step away halves the size.
 * View slots (dx, dy for facing north; F = front face, S = side face of that cell):
 *   0 (0,0) own cell, whole view    1 (-1,0) S   2 (1,0) S
 *   3 (-1,-1) F  4 (0,-1) F  5 (1,-1) F  6 (-2,-1) S  7 (-1,-1) S  8 (1,-1) S  9 (2,-1) S
 *   10-14 (-2..2,-2) F   15 (-3,-2) S  16 (-2,-2) S  17 (-1,-2) S  18 (1,-2) S  19 (2,-2) S  20 (3,-2) S
 *   21-27 (-3..3,-3) F   28 (-2,-3) S  29 (-1,-3) S  30 (1,-3) S  31 (2,-3) S
 * Cell bytes (docs/FORMATS.md 4): >= 80h wall-like: 80-BF a plain wall (so A0, the secret door,
 * looks like a wall), C0-FF a wall with a door; below 80h open: bit 10h ladder up, 20h ladder down,
 * 40h chest; the low nibble (events) is not drawn.
 *
 * This overlay is loaded into EXODUS's memory and uses two of its addresses, EQUs in the assembly
 * (DMAP = 0900h, ROWTAB = 132Ah): EXODUS's DungeonMap (the dungeon: 8 levels of 16 x 16 cells) and
 * ScreenRowTbl (the CGA offset of each scan line, words). The assembly also puts `jmp
 * DrawDungeonView` at 0100, the entry; it is no routine of its own.
 */

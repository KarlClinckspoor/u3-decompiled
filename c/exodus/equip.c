/* asm: FindMonster @7F96
 * The creature slot (0-31) whose MonX, MonY are DL, DH, searched from slot 31 down; empty slots
 * (MonTile 0) are skipped. Returns BX = the slot or 0FFFFh. */
u16 FindMonster(u8 dl, u8 dh)
{
    u16 si = 0x1F;                              /* lea si, MonTile[1Fh]: the last slot */
    for (u16 cx = 0x20; cx != 0; cx--, si--) {
        if (MonTile[si] == 0)                   /* empty */
            continue;
        if (dh != MonY[si])                     /* [si+60h] */
            continue;
        if (dl == MonX[si])                     /* [si+40h] */
            return si;                          /* FindMonster_Found: BX = SI - MonTile */
    }
    return 0xFFFF;
}

/* asm: CmdTransact @7FC6 ignore: Ofs80h -- MonTalk is MonTile + 80h
 * T, "Who will/Transact?". Asks a player and a direction.
 * - A creature there: Lord British (tile 4Ch = shape 19) raises the maximum hit points by 100 (one
 *   level) if the experience's hundreds reach the maximum's hundreds ("Experience more!" if not),
 *   up to 2500 ("No more!"), and from 500 on only with the Mark of Kings ("Seek ye the Mark of
 *   Kings!"). Others answer by their MonTalk byte: 0C0h "Eat Death Scum!", 0 "Good day!", n =
 *   speech n-1 of MapText.
 * - No creature: a counter (map byte 94h-0E4h: a wall or sign letter) with a merchant (40h, shape
 *   16) behind it: the town service for the player's y & 7 (table ShopCmds), or the Equine Emporium
 *   (ShopHorses) when facing west. The player's number is inverted meanwhile.
 * - Otherwise "Not Here!". */
void CmdTransact(const u8 *si)
{
    PrintMsg(si);
    u8 *bx;
    u8 al = AskPlayer(&bx);
    if (al == 0)                                /* ZF: nobody */
        return;                                 /* CmdTransact_Done */
    u16 di = al;                                /* mov di, ax: DI = the player number (AL; AH as the caller left it) */
    u8 *bp = bx;                                /* BP = his record */
    if (!IsUp(bx)) {                            /* jne CmdTransact_Incap */
        MsgIncapacitated();
        return;
    }
    PrintMsg(MsgTalkDirect);                    /* "Direct? " */
    u16 dx, cell;
    if (AskDirection(&dx, &cell))               /* ZF: Esc */
        return;
    u16 cx = dx;                                /* CX = the step */
    dx = cell;                                  /* xchg dx, bx: DX = the cell */
    u16 slot = FindMonster(dx & 0xFF, dx >> 8);
    if (slot == 0xFFFF) {                       /* no creature there */
        u8 *p;
        al = MapCellAddr(dx & 0xFF, dx >> 8, &p);
        if (al < 0x94 || al > 0xE4) {           /* shape 37, Wall ... to 57, sign letter T */
            MsgNotHere();
            return;
        }
        /* one cell further: no wrap at 64 here (add dl, cl / add dh, ch), unlike AskDirection's cell */
        u8 dl = (dx & 0xFF) + (cx & 0xFF);
        u8 dh = (dx >> 8) + (cx >> 8);
        dx = dl | (dh << 8);
        al = MapCellAddr(dx & 0xFF, dx >> 8, &p);
        if (al != 0x40) {                       /* Merchant */
            MsgNotHere();
            return;
        }
        u16 si_num = di;                        /* mov si, di */
        InvertPlayerNum(di & 0xFF);             /* mov ax, di */
        u8 *rec = bp;                           /* DI = the record for the service */
        if (cx == 0xFF) {                       /* step (-1, 0): west */
            ShopHorses(rec);                    /* Equine Emporium */
        } else {
            /* mov al, PlayerY / and al, 7 / shl ax, 1 / mov bx, ax: the entry of the player's y & 7; the
             * service takes DI = the record and is expected to save SI (the number is read back below) */
            ShopCmds[PlayerY & 7](rec);         /* call word ptr ShopCmds[bx] */
        }
        InvertPlayerNum(si_num & 0xFF);         /* CmdTransact_Unmark: mov ax, si */
        return;
    }
    /* CmdTransact_Creature */
    if (MonTile[slot] == 0x4C) {                /* Lord British (shape 19) */
        PrintMsg(MsgWelcomeChild);              /* "Welcome my child" */
        bx = bp;
        al = bx[0x1D];                          /* maximum hit points / 100 */
        if (al > bx[0x1F]) {                    /* experience / 100 */
            PrintMsg(MsgExpMore);               /* "Experience more!" */
            return;
        }
        if (al >= 0x25) {                       /* 2500 (BCD) */
            PrintMsg(MsgNoMore);                /* "No more!" */
            return;
        }
        if (al >= 5) {
            u8 ah = bx[0x0E] & 0x80;            /* Mark of Kings */
            if (ah == 0) {
                PrintMsg(MsgSeekKings);         /* "Seek ye the Mark of Kings!" */
                return;
            }
        }
        /* CmdTransact_LevelUp */
        bool cf = false;
        bx[0x1D] = AddDaa(al, 1, &cf);          /* + 100 maximum hit points */
        PrintMsg(MsgThouGreater);               /* "Thou art greater" */
        FlashView();
        SoundBX = 0x4080;                       /* mov bl, 80h / mov bh, 40h: sound 0FDh's parameters */
        Sound(0xFD);
        FlashView();
        return;
    }
    al = MonTalk[slot];                         /* Ofs80h[bx+di]: MonTile + 80h = MonTalk */
    if (al == 0xC0) {                           /* does not talk: hostile */
        PrintMsg(MsgEatDeath);                  /* "Eat Death Scum!" */
        return;
    }
    al &= 0x3F;
    /* mov cx, 0 / shr al, cl: a shift by 0 does nothing and leaves the flags, so the je below tests the `and` */
    if (al == 0) {
        PrintMsg(MsgGoodDay);                   /* "Good day!" */
        return;
    }
    al--;
    u16 off = Rd(MapText + (al * 2));           /* the speech's offset */
    PrintMsg(MapText + off);
}

/* asm: ChestLoot @80D9
 * The contents of a chest for the player at DI (Get Chest, the dungeon chests, a spell). "Gold+nn":
 * (random(100) | 30h) mod 100, so 48-63 or 12-27 gold (AddGold adds it, at most 9999). Then 1 time
 * in 4 an item: a weapon 1-7 (Dagger to Sword, "and a Dagger") or, failing that, an armour 1-3
 * (Cloth to Chain, "and Leather"), the index being the AND of two random numbers; at most 99 of each. */
void ChestLoot(u8 *di)
{
    PrintMsg(MsgGoldPlus);                      /* "Gold+" */
    u8 dl = Random(0x64);                       /* 0-99 */
    dl |= 0x30;
    if (dl >= 0x64)
        dl -= 0x64;
    u8 al = ToBcd(dl);                          /* aam / shl ah, 4 / or al, ah */
    PrintBcdByte(al);
    ScrollMsg();
    AddGold(al, di);                            /* gold += AL */
    dl = Random(0xFF);
    if (dl >= 0x40)                             /* 1 in 4: an item */
        return;                                 /* ChestLoot_Done */
    dl = Random(0xFF);
    if (!(dl & 0x80)) {                         /* test dl, 0FFh / js ChestLoot_TryArmour */
        al = dl;
        dl = Random(0xFF);
        dl &= al;
        dl &= 7;                                /* weapon 1-7 */
        if (dl != 0) {
            PrintMsg(MsgAndA);                  /* "and a " */
            PrintName(dl + 0x41);               /* name 40h+n: a weapon */
            ScrollMsg();
            bool cf = false;
            di[dl + 0x30] = AddDaa(di[dl + 0x30], 1, &cf);      /* weapons owned */
            if (cf)
                di[dl + 0x30] = 0x99;
            return;
        }
    }
    /* ChestLoot_TryArmour */
    dl = Random(0xFF);
    if (dl & 0x80)
        return;
    al = dl;
    dl = Random(0xFF);
    dl &= al;
    dl &= 3;                                    /* armour 1-3 */
    if (dl == 0)
        return;
    PrintMsg(MsgAnd);                           /* "and " */
    PrintName(dl + 0x51);                       /* name 50h+n: an armour */
    ScrollMsg();
    bool cf = false;
    di[dl + 0x28] = AddDaa(di[dl + 0x28], 1, &cf);              /* armours owned */
    if (cf)
        di[dl + 0x28] = 0x99;
}

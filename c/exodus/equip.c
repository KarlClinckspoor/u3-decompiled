/* asm: ReadyWeapon @7E48
 * "Weapon:" and the weapon menu for the player at BX (10, 17 or 18 entries by ExoticWeaponFound /
 * ExtraWeaponsOk). The class allows keys below its entry in MaxWeaponTbl; Exotic (P) is always
 * allowed, Hand (A) needs nothing owned, other weapons need a count > 0. Prints "Readied!" and
 * sets record byte 30h. Also used by combat. */
void ReadyWeapon(u8 *bx)
{
    PrintMsg(MsgWeaponPrompt);                  /* "Weapon:" */
    u16 cx = 0x0B;                              /* 11 classes */
    u16 si = cx;
    const u8 *di = ClassLetters;
    u8 al = bx[0x17];                           /* class */
    while (cx != 0) {                           /* repne scasb */
        u8 b = *di++;
        cx--;
        if (b == al) break;
    }
    si = si - cx - 1;                           /* sub si, cx / dec si: the class's index */
    u8 dl = MaxWeaponTbl[si];                   /* the first key not allowed */
    cx = 0x12;
    if (ExoticWeaponFound != 0xFF) {
        cx = 0x11;
        if (ExtraWeaponsOk != 0xFF)
            cx = 0x0A;
    }
    al = AskChoice(cx, WeaponMenuKeys, WeaponMenuStrs);
    if (al == 0x51 || al == 0x1B) {             /* 'Q', Esc: ReadyWeapon_Quit */
        ScrollMsg();
        return;
    }
    if (al != 0x50 && al >= dl) {               /* 'P' Exotic is always allowed; cmp al, dl / jae */
        PrintMsg(MsgNotAllowed);                /* "Not allowed!" */
        Sound(0xFF);
        return;
    }
    /* ReadyWeapon_Pick */
    u8 *di_rec = bx;                            /* mov di, bx */
    al -= 0x41;                                 /* index; 0 = Hand */
    if (al != 0) {                              /* je ReadyWeapon_Set */
        if (bx[al + 0x30] == 0) {               /* add bx, ax / cmp byte ptr [bx+30h], 0: the count owned */
            ScrollMsg();                        /* ReadyWeapon_NoneOwned */
            PrintMsg(MsgNoneOwned);             /* "None owned" */
            Sound(0xFF);
            return;
        }
    }
    PrintMsg(MsgReadied);                       /* ReadyWeapon_Set: "Readied!" */
    di_rec[0x30] = al;                          /* weapon readied */
}


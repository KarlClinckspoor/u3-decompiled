static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }

/* asm: ReadAmount @7D1A
 * Reads a number of up to 4 digits at the cursor (the field is blanked and read again until it
 * holds a number). Returns AX = the number as BCD (ParseNumber's BX). The assembly keeps the 4
 * characters at [bp+2] and the cursor position at [bp] on the stack. */
u16 ReadAmount(void)
{
    u8 chars[4];                                /* [bp+2]: the 4 characters */
    u16 dx = SwapCursor(0);                     /* mov dx, 0 / call SwapCursor: the cursor goes to 0,0; DX = the old one */
    u16 cursor = dx;                            /* [bp]: the cursor position */
    for (;;) {
        SwapCursor(dx);                         /* ReadAmount_Retry: back to the field */
        PutChar(0x20);                          /* blank the field */
        PutChar(0x20);
        PutChar(0x20);
        PutChar(0x20);
        dx = cursor;
        SwapCursor(dx);                         /* to the start of the field again */
        u16 bx = ReadLine(chars, 4);            /* BX = the characters typed */
        dx = ParseNumber(chars, bx, &bx);       /* mov cx, bx / mov si, di: BX = the value, DX = decimal / -1 / -2 */
        if (!(dx & 0x8000))                     /* or dx, dx / jns: DX < 0 means no number */
            return bx;                          /* the BCD value */
        Sound(0xFE);                            /* error beep */
        dx = cursor;
    }
}

/* asm: TransferBcd @7D74
 * Moves AX from CX to DX, all BCD words: CX -= AX, DX += AX. Returns AX: 0 done, 1 CX too small,
 * 2 DX would pass 9999 (CX, DX unchanged then). For byte counts the callers pass AH = CH = DH = 0
 * and test DH <> 0 for "more than 99". */
u16 TransferBcd(u16 ax, u16 *cx, u16 *dx)
{
    u8 bl = ax & 0xFF, bh = ax >> 8;            /* mov bx, ax: the amount */
    if (ax > *cx)                               /* cmp ax, cx: BCD compares like binary / ja */
        return 1;                               /* TransferBcd_Short */
    bool cf = false;
    u8 lo = AddDaa(bl, *dx & 0xFF, &cf);        /* add al, dl / daa */
    u8 hi = AddDaa(bh, *dx >> 8, &cf);          /* xchg ah, al / adc al, dh / daa */
    if (cf)                                     /* jb TransferBcd_Full */
        return 2;
    u16 sum = lo | (hi << 8);                   /* xchg ah, al / mov dx, ax */
    cf = false;
    lo = SubDas(*cx & 0xFF, bl, &cf);           /* mov ax, cx / sub al, bl / das */
    hi = SubDas(*cx >> 8, bh, &cf);             /* xchg ah, al / sbb al, bh / das / xchg ah, al */
    *dx = sum;
    *cx = lo | (hi << 8);
    return 0;
}


/* asm: GuildGems @ABBD returns: ShopGuild_Done -- buy AL (BCD, from ReadNumber; AH = the same number
 * in binary) gems at 75 g.p.; the price is computed in binary, rate * count, and turned into a BCD word */
void GuildGems(u8 *di)
{
    PrintMsg(MsgGuildHowMany);
    u16 ax = ReadNumber();                      /* AL = count (BCD), AH = count (binary), 0FFh: Esc */
    if ((ax >> 8) == 0xFF) {
        ShopGuild_Cancel();
        return;
    }
    u8 bh = ax >> 8;
    bool cf = false;
    u8 bl = AddDaa(ax & 0xFF, di[0x25], &cf);   /* gems (25h) + count */
    if (cf) {                                   /* over 99 */
        ShopGuild_TooMuch();
        return;
    }
    u16 total = 75 * bh;                        /* 75 g.p. a gem, times the binary count */
    u16 price = ToBcd(total / 100) << 8 | ToBcd(total % 100);   /* div 100: hundreds in AH, the rest in AL */
    if (PayGold(di, price)) {                   /* CF: not enough */
        ShopGuild_NoFunds();
        return;
    }
    di[0x25] = bl;                              /* new number of gems */
    ShopGuild_More(di);
}


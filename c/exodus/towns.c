/* asm: GuildPowders @AC6B returns: ShopGuild_Done -- powders at [di+27h], 90 g.p. each */
void GuildPowders(u8 *di)
{
    PrintMsg(MsgGuildHowMany);
    u16 ax = ReadNumber();
    if ((ax >> 8) == 0xFF) {
        ShopGuild_Cancel();
        return;
    }
    u8 bh = ax >> 8;
    bool cf = false;
    u8 bl = AddDaa(ax & 0xFF, di[0x27], &cf);   /* powders (27h) + count */
    if (cf) {
        ShopGuild_TooMuch();
        return;
    }
    u16 total = 90 * bh;                        /* 90 g.p. a powder */
    u16 price = ToBcd(total / 100) << 8 | ToBcd(total % 100);
    if (PayGold(di, price)) {                   /* jae GuildPowders_Paid, else: */
        ShopGuild_NoFunds();
        return;
    }
    di[0x27] = bl;                              /* new number of powders */
    ShopGuild_More(di);
}


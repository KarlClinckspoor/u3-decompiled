/* asm: ShopWeapons @A8A5 */
void ShopWeapons(u8 *di)
{
    PrintMsg(MsgWeaponsShop);
    if (AskYesNo() != 0x4E)                     /* List? */
        ShopListWeapons();
    PrintMsg(MsgBuyOrSell);                     /* ShopWeapons_BuySell */
    u8 al = AskChoice(4, BuySellMenuKeys, BuySellMenuStrs);     /* four keys: B S Q Esc */
    ScrollMsg();
    if (al == 0x51 || al == 0x1B)               /* Q, Esc */
        return;
    u16 cx;
    if (al != 0x42) {                           /* not 'B': sell (ShopWeapons_Sell) */
        for (;;) {
            PrintMsg(MsgForSale);
            cx = 0x0A;                          /* weapon keys Q Esc 0 B-H */
            if (PartyXY[0] == 0x25 && ExtraWeaponsOk != 0)  /* in Dawn, and the list was shown there */
                cx = 0x11;                      /* Q Esc 0 B-O */
            al = AskChoice(cx, ShopWeaponKeys, WeaponMenuStrs);
            if (al == 0x51 || al == 0x1B) {     /* ShopWeapons_Scroll */
                ScrollMsg();
                return;
            }
            u8 n = al - 0x42;                   /* 'B' = weapon 1 (Dagger); BX = n */
            u8 dl = di[0x31 + n];               /* count owned of that weapon (31h-3Fh) */
            if (dl == 0) {                      /* ShopWeapons_NotOwned */
                PrintMsg(MsgDontOwn);
                Sound(0xFE);                    /* ShopWeapons_Beep */
                return;
            }
            u16 price = WeaponPrices[n * 2] | (WeaponPrices[n * 2 + 1] << 8);  /* its price (BCD word) */
            bool cf;
            u16 gold = AddBcdWord(GoldOf(di), price, &cf);  /* gold (23-24) += price */
            if (cf) {                           /* past 9999: ShopWeapons_TooMuchGold */
                PrintMsg(MsgTooMuchGold);
                Sound(0xFE);
                return;
            }
            di[0x23] = gold & 0xFF;             /* ShopWeapons_Sold */
            di[0x24] = gold >> 8;
            bool bf = false;
            di[0x31 + n] = SubDas(dl, 1, &bf);  /* count - 1 (BCD) */
            di[0x30] = 0;                       /* weapon readied = 0 (Hand), whichever weapon was sold */
            PrintMsg(MsgThankYou);
        }
    }
    for (;;) {                                  /* ShopWeapons_Buy */
        PrintMsg(MsgYourInterest);
        cx = 0x0A;                              /* weapon keys Q Esc 0 B-H */
        if (PartyXY[0] == 0x25 && ExtraWeaponsOk != 0)      /* in Dawn, and the list was shown there */
            cx = 0x11;                          /* Q Esc 0 B-O */
        al = AskChoice(cx, ShopWeaponKeys, WeaponMenuStrs);
        if (al == 0x51 || al == 0x1B) {         /* ShopWeapons_Scroll */
            ScrollMsg();
            return;
        }
        u8 n = al - 0x42;
        u8 dl = di[0x31 + n];                   /* count owned */
        if (dl == 0x99) {                       /* 99: no more room (ShopWeapons_NoRoom) */
            PrintMsg(MsgShopNoMoreRoom);
            Sound(0xFE);
            return;
        }
        u16 price = WeaponPrices[n * 2] | (WeaponPrices[n * 2 + 1] << 8);
        if (PayGold(di, price)) {               /* CF: not enough (ShopWeapons_NoGold) */
            PrintMsg(MsgHaventTheGold);
            Sound(0xFE);
            return;
        }
        bool cf = false;
        di[0x31 + n] = AddDaa(dl, 1, &cf);      /* count + 1 (BCD) */
        PrintMsg(MsgHereYouAre);
    }
}


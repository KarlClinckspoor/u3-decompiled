/* asm: ShopRadrion @ACFC */
void ShopRadrion(u8 *di)
{
    PrintMsg(MsgRadrion);
    for (;;) {                                  /* ShopRadrion_Ask */
        PrintMsg(MsgHowMany100gp);
        u16 ax = ReadNumber();                  /* AL = hundreds (BCD), AH = 0FFh: Esc */
        if ((ax >> 8) == 0xFF) {                /* ShopRadrion_Cancel */
            ScrollMsg();
            PrintMsg(TxtWhat);                  /* the cancel message of HAND (TxtWhat) */
            Sound(0xFE);                        /* ShopRadrion_Beep */
            return;
        }
        ScrollMsg();
        ScrollMsg();
        ax = (ax & 0xFF) << 8;                  /* AX = hundreds * 100 (BCD word) */
        if (PayGold(di, ax)) {                  /* CF: not enough (ShopRadrion_CantPay) */
            PrintMsg(MsgCantPay);
            Sound(0xFE);
            return;
        }
        /* BUG, as in the original: the verse is OracleVerses[the BCD value of the hundreds read as a
         * binary number] (shr ax, 8), so an offer of 10 hundred or more (BCD 10h-99h) indexes past
         * the 10-entry table and the "pointer" is taken from the words that follow in the data. */
        PrintMsg(OracleVerses[ax >> 8]);
        PrintMsg(MsgMoreOffering);
        u8 al = AskYesNo();
        ScrollMsg();
        if (al == 0x59)                         /* 'Y' */
            continue;
        ScrollMsg();
        PrintMsg(MsgGoodLuck);
        return;
    }
}

/* asm: ShopHorses @AD70 -- PartySize horses for PartySize * 200 g.p. */
void ShopHorses(u8 *di)
{
    PrintMsg(MsgEquineEmporium);
    u8 al = PartySize;
    PrintDigit(al);                             /* "n horses cost" */
    PrintMsg(MsgHorsesCost);
    al <<= 1;                                   /* 2n: "2n00gp" (one digit: up to 8) */
    PrintDigit(al);
    PrintMsg(MsgWillYouBuy);
    u8 ah = al;                                 /* AH = 2n (BCD hundreds); AskYesNo keeps AH */
    if (AskYesNo() == 0x4E) {                   /* 'N' (ShopHorses_Declined) */
        PrintMsg(MsgTooBad);
        return;
    }
    if (PayGold(di, (u16)ah << 8)) {            /* AX = 2n * 100 (BCD); CF: not enough */
        PrintMsg(MsgNotGoldEnough);             /* ShopHorses_NoGold */
        Sound(0xFF);
        return;
    }
    PrintMsg(MsgRideFast);
    PartyTile[0] = 0x0A;                        /* the party's tile: 0Ah horse */
}

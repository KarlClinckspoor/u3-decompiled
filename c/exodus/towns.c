/* asm: TempleCure @A6D4 returns: ShopTemple_Done -- 100 g.p. to cure poison */
void TempleCure(u8 *di)
{
    PrintMsg(MsgCuringCost);
    if (AskYesNo() == 0x4E) {                   /* 'N' */
        ShopTemple_NoOffering();
        return;
    }
    if (GoldOf(di) < 0x100) {                   /* gold (23-24, BCD) < 100? */
        ShopTemple_NoGold();
        return;
    }
    PrintMsg(MsgTempleCureWhom);
    u8 *bx;
    u8 al = AskPlayer(&bx);                     /* BX = the target's record, AL = 1-4; ZF: Esc */
    if (al == 0)
        return;                                 /* je ShopTemple_Done */
    u8 cx = al - 1;                             /* the target's number (0-3) */
    if (bx[0x11] == 0x47) {                     /* status (11h) 'G' good */
        ShopTemple_NotInjured();
        return;
    }
    FlashView();                                /* flash the map window and his status box ? */
    FlashPlayer(cx);
    SoundBX = 0x80C0;                           /* BL = 0C0h, BH = 80h (BX is pushed around it) */
    Sound(0xFD);                                /* the temple's sound */
    FlashPlayer(cx);                            /* flash both back */
    FlashView();
    if (bx[0x11] != 0x50) {                     /* 'P' poisoned? */
        ShopTemple_Failed();
        return;
    }
    bx[0x11] = 0x47;                            /* status = 'G' */
    PayGold(di, 0x100);                         /* 100 g.p. (BCD) */
    ShopTemple_Farewell();
}


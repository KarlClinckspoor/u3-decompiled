/* The record's fields that the shops use: gold (BCD word) at +23h. */
static u16 GoldOf(const u8 *di) { return di[0x23] | (di[0x24] << 8); }

/* BCD word + BCD word (add/daa, adc/daa on the two bytes); *cf = carry past 9999. */
static u16 AddBcdWord(u16 a, u16 b, bool *cf)
{
    *cf = false;
    u8 lo = AddDaa(a & 0xFF, b & 0xFF, cf);
    u8 hi = AddDaa(a >> 8, b >> 8, cf);
    return lo | (hi << 8);
}

/* asm: ShopPub @A5AC */
void ShopPub(u8 *di)
{
    PrintMsg(MsgWelcomePub);
    for (;;) {                                  /* ShopPub_Again */
        PrintMsg(MsgHaveADrink);
        u16 ax = ReadNumber();                  /* AL = amount (BCD), AH = 0FFh: Esc */
        if ((ax >> 8) == 0xFF) {                /* ShopPub_Cancel */
            ScrollMsg();
            PrintMsg(TxtWhat);                  /* the cancel message of HAND (TxtWhat) */
            Sound(0xFE);                        /* ShopPub_Beep: refused sound */
            return;
        }
        ScrollMsg();
        if ((ax & 0xFF) < 7) {                  /* less than 7 g.p.? */
            PrintMsg(MsgLeaveMyShop);
            Sound(0xFF);                        /* failure sound */
            return;
        }
        ax &= 0xFF;                             /* mov ah, 0 (ShopPub_Pay) */
        if (ax >= GoldOf(di)) {                 /* amount >= gold: can't pay (even exactly all of it) */
            PrintMsg(MsgCantPay);
            Sound(0xFE);
            return;
        }
        ScrollMsg();
        PayGold(di, ax);                        /* AX = amount; CF cannot be set here */
        PrintMsg(PubTips[ax >> 4]);             /* the tens digit selects the tip (shr ax, 4; shl si, 1) */
        PrintMsg(MsgAnother);
        u8 al = AskYesNo();
        ScrollMsg();
        if (al == 0x59)                         /* 'Y' */
            continue;
        PrintMsg(MsgBeenAPleasure);
        return;
    }
}

/* asm: ShopGrocer @A630 */
void ShopGrocer(u8 *di)
{
    PrintMsg(MsgGrocer);
    u16 ax = ReadAmount();                      /* AX = number of rations (BCD), 0 = none */
    if (ax != 0) {
        if (ax > GoldOf(di)) {                  /* more than his gold? (ShopGrocer_CantPay) */
            PrintMsg(MsgCantPay);
            Sound(0xFF);
            return;
        }
        u16 food = di[0x21] | (di[0x22] << 8);  /* keep the old food */
        bool cf;
        u16 sum = AddBcdWord(food, ax, &cf);    /* food (21-22, BCD word) += rations */
        if (cf) {                               /* past 9999: too much (ShopGrocer_TooMuch) */
            PrintMsg(MsgTooMuchToCarry);
            di[0x21] = food & 0xFF;             /* put the old food back */
            di[0x22] = food >> 8;
            Sound(0xFF);
            return;
        }
        di[0x21] = sum & 0xFF;
        di[0x22] = sum >> 8;
        PayGold(di, ax);                        /* 1 g.p. a ration */
        StatusLine();
    }
    PrintMsg(MsgGrocerThanks);                  /* ShopGrocer_Thanks */
}


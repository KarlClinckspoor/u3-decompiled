/* ---- helpers that are not routines of the game: words in memory ---- */

static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }
static void Wr(u8 *p, u16 w) { p[0] = w & 0xFF; p[1] = w >> 8; }

/* asm: AskDirection @7AEA
 * Reads an arrow key (others beep) and prints North/South/East/West. Returns ZF (true = Esc:
 * DX = 0, BX = PlayerXY); DX = the step (DL x, DH y: -1, 0, +1) and BX = PlayerXY + step wrapped
 * at 64 (BL x, BH y) through the pointers. ZF is `test dx, 0FFFFh`: set exactly when DX is 0. */
bool AskDirection(u16 *pdx, u16 *pbx)
{
    u16 bx = PlayerXY | (PlayerY << 8);         /* mov bx, word ptr PlayerXY */
    u8 dl = 0, dh = 0;                          /* mov dx, 0 */
    for (;;) {                                  /* AskDirection_Key */
        u16 ax = ReadKey();
        if (ax == 0x4800) {                     /* Up */
            PrintMsg(MsgMoveNorth);
            dh = 0xFF;
            break;
        }
        if (ax == 0x5000) {                     /* Down */
            PrintMsg(MsgMoveSouth);
            dh = 1;
            break;
        }
        if (ax == 0x4D00) {                     /* Right */
            PrintMsg(MsgMoveEast);
            dl = 1;
            break;
        }
        if (ax == 0x4B00) {                     /* Left */
            PrintMsg(MsgMoveWest);
            dl = 0xFF;
            break;
        }
        if (ax == 0x011B) {                     /* Esc */
            ScrollMsg();                        /* AskDirection_Esc */
            break;
        }
        Sound(0xFE);                            /* error beep */
    }
    /* AskDirection_Done */
    u8 bl = (bx & 0xFF) + dl;
    u8 bh = (bx >> 8) + dh;
    bx = (bl | (bh << 8)) & 0x3F3F;
    *pdx = dl | (dh << 8);
    *pbx = bx;
    return *pdx == 0;                           /* test dx, 0FFFFh: ZF = no step (Esc) */
}

/* asm: HandEquip @7B54
 * The Hand Equipment menu "F, G, E, W, A:" from the player at SI to the player at DI. Ends with
 * "Done!" or an error, then StatusLine. The pops at the end swap AX and BX on the way out (the
 * caller does not care). */
void HandEquip(u8 *si, u8 *di)
{
    PrintMsg(MsgHandMenu);                      /* "F, G, E, W, A:" */
    u8 al = AskChoice(7, HandMenuKeys, HandMenuStrs);   /* keys F G E W A Q Esc */
    const u8 *p = HandCmdKeys;                  /* the same keys in the order of the handlers */
    u16 cx = 7;
    u16 bx;
    while (cx != 0) {                           /* repne scasb */
        u8 b = *p++;
        cx--;
        if (b == al) break;
    }
    bx = 7 - cx - 1;                            /* sub bx, cx / dec bx: the key's index (6 if none matched) */
    /* mov si, [bp+2] / mov di, [bp] / jmp HandCmds[bx*2]: the handler finishes HandEquip (HandQuit,
     * which takes no parameters, is two of the entries: it ignores the two records) */
    HandCmds[bx](si, di);
}

/* asm: HandEquip_Done @7B8E
 * "Done!", then the end of the menu (falls into HandQuit). */
void HandEquip_Done(void)
{
    PrintMsg(MsgDone);                          /* "Done!" */
    HandQuit();
}

/* asm: HandQuit @7B95
 * The end of the Hand menu (also its Q and Esc entries). */
void HandQuit(void)
{
    ScrollMsg();
    HandEquip_Exit();
}

/* asm: HandEquip_Exit @7B98
 * StatusLine, then HandEquip restores the registers and returns to its caller. */
void HandEquip_Exit(void)
{
    StatusLine();
}

/* asm: HandGold @7BA4
 * "How much?", 4 digits; moves that much gold (record 23h) from the giver to the receiver.
 * HandFood (7BA9) is the same with food (21h, a word: whole units, the hundredths stay) and
 * enters at HandGold_Ask. */
void HandGold(u8 *si, u8 *di)
{
    u16 bx = 0x23;                              /* gold */
    HandGold_Ask(si, di, bx);
}

/* asm: HandFood @7BA9 */
void HandFood(u8 *si, u8 *di)
{
    u16 bx = 0x21;                              /* food */
    HandGold_Ask(si, di, bx);
}

/* asm: HandGold_Ask @7BAC
 * The shared part of HandGold and HandFood; BX = the record offset the caller left. */
void HandGold_Ask(u8 *si, u8 *di, u16 bx)
{
    PrintMsg(MsgHowMuch);                       /* "How much? " */
    u16 ax = ReadAmount();                      /* up to 4 digits, BCD */
    u16 cx = Rd(si + bx);                       /* the giver's */
    u16 dx = Rd(di + bx);                       /* the receiver's */
    ax = TransferBcd(ax, &cx, &dx);
    if (ax == 1) {
        HandEquip_NotEnough();
        return;
    }
    if (ax == 2) {
        HandEquip_NoRoom();
        return;
    }
    Wr(si + bx, cx);
    Wr(di + bx, dx);
    HandEquip_Done();
}

/* asm: HandItems @7BD0 also: @7C26
 * "G, K, P, T:" gems (25h), keys (26h), powders (27h) or torches (0Fh), "How much?" (2 digits),
 * at most 99 for the receiver. (HandItems_Ask, 7C26, lies after the shared exits.) */
void HandItems(u8 *si, u8 *di)
{
    PrintMsg(MsgHandEquipMenu);                 /* "G, K, P, T:" */
    u8 al = AskChoice(6, HandEquipKeys, HandEquipStrs);
    u16 bx;
    if (al == 0x47)                             /* 'G' */
        bx = 0x25;                              /* gems */
    else if (al == 0x4B)                        /* 'K' */
        bx = 0x26;                              /* keys */
    else if (al == 0x50)                        /* 'P' */
        bx = 0x27;                              /* powders */
    else if (al == 0x54)                        /* 'T' */
        bx = 0x0F;                              /* torches */
    else {
        HandQuit();                             /* Q, Esc */
        return;
    }
    /* HandItems_Ask */
    PrintMsg(MsgHowMuch);                       /* "How much? " */
    u16 ax = ReadNumber();                      /* AL = the BCD value, AH = 0FFh: no number */
    if ((ax >> 8) == 0xFF) {
        HandEquip_BadNum();
        return;
    }
    ax &= 0xFF;                                 /* mov ah, 0 */
    u16 cx = si[bx];
    u16 dx = di[bx];
    ax = TransferBcd(ax, &cx, &dx);             /* byte counts: CH = DH = 0 */
    if (ax == 1) {
        HandEquip_NotEnough();
        return;
    }
    if ((dx >> 8) != 0) {                       /* more than 99 */
        HandEquip_NoRoom();
        return;
    }
    si[bx] = cx & 0xFF;
    di[bx] = dx & 0xFF;
    HandEquip_Done();
}

/* asm: HandEquip_NotEnough @7C03 */
void HandEquip_NotEnough(void)
{
    HandEquip_Fail(MsgNotEnough);               /* "Not enough!" */
}

/* asm: HandEquip_NoRoom @7C09 */
void HandEquip_NoRoom(void)
{
    ScrollMsg();
    PrintMsg(MsgNoMoreRoom);                    /* "No more room!" */
    Sound(0xFE);
    HandEquip_Exit();                           /* not HandQuit: no second ScrollMsg */
}

/* asm: HandEquip_Fail @7C1B
 * The message in SI (left by the caller), a beep, the end of the menu. */
void HandEquip_Fail(const u8 *si)
{
    PrintMsg(si);
    Sound(0xFE);
    HandQuit();
}

/* asm: HandEquip_BadNum @7C59 */
void HandEquip_BadNum(void)
{
    Sound(0xFE);
    HandQuit();
}

/* asm: HandWeapons @7C61
 * Picks a weapon from the menu (as many entries as the flags allow: 18 up to Exotic, 17 up to
 * +4 Swd, 10 up to 2-H-Swd), "How many?" (2 digits) and moves them. Hand ('A') cannot be given
 * ("<-What?"); the giver's readied weapon: "In use!". HandArmour (7C85) does the same for armour. */
void HandWeapons(u8 *si, u8 *di)
{
    u16 bx = 0x30;                              /* weapons (30h + index) */
    u16 cx = 0x12;                              /* 18 entries: up to Exotic */
    if (ExoticWeaponFound != 0xFF) {
        cx = 0x11;                              /* 17: up to +4 Swd */
        if (ExtraWeaponsOk != 0xFF)
            cx = 0x0A;                          /* 10: up to 2-H-Swd */
    }
    /* HandWeapons_Menu */
    HandArms_Pick(si, di, bx, cx, WeaponMenuKeys, WeaponMenuStrs);
}

/* asm: HandArmour @7C85 */
void HandArmour(u8 *si, u8 *di)
{
    u16 bx = 0x28;                              /* armours (28h + index) */
    u16 cx = 0x0A;                              /* 10: up to Exotic */
    if (ExoticArmourFound != 0xFF) {
        cx = 9;                                 /* 9: up to +2 Plate */
        if (ExtraArmoursOk != 0xFF)
            cx = 7;                             /* 7: up to Plate */
    }
    /* HandArmour_Menu */
    HandArms_Pick(si, di, bx, cx, ArmourMenuKeys, ArmourMenuStrs);
}

/* asm: HandArms_Pick @7CA7
 * The shared menu of HandWeapons and HandArmour: BX = 30h / 28h (the record offset of the
 * weapons / armours), CX = the number of entries, DI = the keys, SI = the strings (the registers
 * the two callers leave; the C passes the two records as well, which the assembly reloads from
 * HandEquip's frame). */
void HandArms_Pick(u8 *si, u8 *di, u16 bx, u16 cx, const u8 *keys, const u8 *const *strs)
{
    ScrollMsg();
    u8 al = AskChoice(cx, keys, strs);
    if (al == 0x41) {                           /* 'A': Hand or Skin */
        /* HandArms_What: BUG, as in the original: MsgWhat ends with `jmp MainLoop`, which does not
         * reset SP, so the 18 bytes HandEquip pushed (flags, 7 registers, the return address) stay on the stack */
        MsgWhat();
        return;
    }
    if (al == 0x51 || al == 0x1B) {             /* 'Q', Esc: HandArms_Quit */
        HandQuit();
        return;
    }
    u16 dx = al;                                /* mov dl, al */
    PrintMsg(MsgHowMany);                       /* "How many? " */
    u16 ax = ReadNumber();                      /* AL = the BCD value, AH = 0FFh: no number */
    if ((ax >> 8) == 0xFF) {
        HandEquip_BadNum();
        return;
    }
    if ((ax & 0xFF) == 0) {                     /* none: HandArms_Quit */
        HandQuit();
        return;
    }
    dx = (dx - 0x41) & 0xFF;                    /* the index (DH = 0) */
    u8 ah = si[bx];                             /* the giver's weapon readied / armour worn */
    bx += dx;
    if (ah == (dx & 0xFF)) {                    /* HandArms_InUse */
        Sound(0xFE);
        PrintMsg(MsgInUse);                     /* "In use!" */
        HandQuit();
        return;
    }
    ax &= 0xFF;                                 /* mov ah, 0 */
    u16 cnt = si[bx];                           /* the counts owned (CH = DH = 0) */
    u16 dst = di[bx];
    ax = TransferBcd(ax, &cnt, &dst);
    if (ax == 1) {                              /* HandArms_NotEnough */
        HandEquip_NotEnough();
        return;
    }
    if ((dst >> 8) != 0) {                      /* more than 99: HandArms_NoRoom */
        HandEquip_NoRoom();
        return;
    }
    si[bx] = cnt & 0xFF;
    di[bx] = dst & 0xFF;
    HandEquip_Done();
}

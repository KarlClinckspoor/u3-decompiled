/* hand.c: HAND.ASM (src/exodus/HAND.ASM), the H command, Hand Equipment, and its menus (7AEA-7D1A).
 *
 * LOOP's handler asks the giver and the receiver and calls HandEquip, the menu: Food, Gold,
 * Equipment (gems, keys, powders, torches), Weapons, Armour. The amounts are moved by TransferBcd
 * (EQUIP), read by ReadAmount (4 digits) or ReadNumber (2). The menus' strings and key lists are
 * in ACTIONS. Also here: AskDirection, the direction prompt every command uses (Look, Bribe,
 * Transact, ...).
 *
 * The handlers (HandGold ... HandArmour) are reached by `jmp HandCmds[bx]` from HandEquip and find
 * the two player records on HandEquip's stack frame ([bp+2] = the giver, SI; [bp] = the receiver,
 * DI); in the C HandEquip calls one with the two records as parameters and returns. They end by
 * jumping to the exits that finish HandEquip (Done!, an error message, HandQuit): in the C each
 * handler calls the exit as its last act and returns, so what follows is only the C unwinding.
 */

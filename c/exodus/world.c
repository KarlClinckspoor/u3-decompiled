/* asm: AdvanceMoons @20AE ignore: CursorCol -- SwapCursor/SetCursor stand for the word access */
void AdvanceMoons(void)
{
    u8 dl, dh, al;
    u8 *cell;
    u16 old;

    if (Location == 0) {                        /* on Sosaria only */
        dl = Moon1Phase;                        /* push word ptr Moon1Phase: the old phases, DL = moon 1, DH = moon 2 */
        dh = Moon2Phase;
        Moon1Count--;
        if ((i8)Moon1Count < 0) {               /* jns: the count ran out */
            Moon1Count = 0x0B;                  /* 12 steps a phase */
            Moon1Phase++;
            Moon1Phase &= 7;
        }
        Moon2Count--;
        if ((i8)Moon2Count < 0) {
            Moon2Count = 3;                     /* 4 steps a phase */
            Moon2Phase++;
            Moon2Phase &= 7;
        }
        if (dh != Moon2Phase) {                 /* moon 2 unchanged: the gate stays */
            al = GateYTbl[dl];                  /* the gate of the old moon 1 phase ... */
            MapCellAddr(GateXTbl[dl], al, &cell);
            *cell = 4;                          /* ... back to grass */
            al = GateYTbl[Moon1Phase];          /* the gate of the new phase */
            MapCellAddr(GateXTbl[Moon1Phase], al, &cell);
            *cell = 0x88;                       /* moon gate (shape 34) */
            al = dl & dh;                       /* both old phases 7: */
            if (al == 7) {
                DawnCell = 0x18;                /* Dawn (37, 53) appears: Towne (shape 6) */
            } else if ((dl | dh) == 0) {        /* both old phases 0: */
                DawnCell = 0x0C;                /* Dawn vanishes: forest (shape 3) */
            }
        }
    }
    /* Moons_Print: row 0, column 8 */
    old = SwapCursor(0x0008);                   /* mov dx, 8 / xchg word ptr CursorCol, dx */
    PutChar(0x10);                              /* a moon symbol */
    PutChar(0x28);                              /* '(' */
    PrintDigit(Moon1Phase);
    PutChar(0x29);                              /* ')' */
    PutChar(0x28);
    PrintDigit(Moon2Phase);
    PutChar(0x29);
    PutChar(0x11);                              /* the other moon symbol */
    SetCursor(old);                             /* mov word ptr CursorCol, dx */
}

/* asm: Whirlpool @2168 */
void Whirlpool(void)
{
    u8 dl;
    u8 *cell;
    u8 m1, m2;

    PartyTile[0] = 0x0C;                        /* draw the party as a whirlpool */
    BuildView();
    PartyTile[0] = 0x0B;                        /* frigate again */
    PrintMsg(MsgWhirlpool);
    Sound(0xF4);                                /* sound 0F4h */
    if (Location == 0xFF) {                     /* in Ambrosia already: Whirlpool_Back */
        PrintMsg(MsgAllIsDark);                 /* "All is Dark!" */
        ClearView();
        LoadFile(MapBuf, 0x1228, FileSosariaUlt);
        PrintMsg(MsgYouMadeIt);                 /* "You made it!" */
        PlayerXY = PartyXY[0];                  /* the party back at its saved place: mov ax, word ptr PartyXY */
        PlayerY = PartyXY[1];
        Location = 0;
        PartyTile[0] = 0x0B;                    /* in a frigate again */
        SaveParty();
        FlushKeys();                            /* Whirlpool_Done */
        return;
    }
    PartyXY[0] = PlayerXY;                      /* remember where the party was: mov word ptr PartyXY, bx */
    PartyXY[1] = PlayerY;
    MapCellAddr(PlayerXY, PlayerY, &cell);
    *cell = 0;                                  /* the frigate is lost: water */
    dl = Random(0x37);                          /* a new place for the whirlpool: y = 7-3Dh, x = 3 */
    dl += 7;
    WhirlpoolX = 3;                             /* WhirlpoolX/WhirlpoolY are really the whirlpool's x and y (PARTY 736C) */
    WhirlpoolY = dl;
    SaveSosaria();                              /* save Sosaria and the party */
    ClearView();
    PrintMsg(MsgIntoDarkness);
    m1 = Moon1Phase;                            /* push word ptr Moon1Phase: the moons' phases are kept */
    m2 = Moon2Phase;
    LoadFile(MapBuf, 0x1228, FileAmbrosiaUlt);
    Moon1Phase = m1;                            /* pop word ptr Moon1Phase */
    Moon2Phase = m2;
    PartyTile[0] = 0x3F;                        /* on foot */
    PlayerXY = 0x20;                            /* mov word ptr PlayerXY, 3620h: x 32, y 54 */
    PlayerY = 0x36;
    Location = 0xFF;                            /* Ambrosia */
    PrintMsg(MsgForgottenLand);
    BuildView();
    FlushKeys();                                /* Whirlpool_Done */
}

/* asm: MonCanEnter @2228 */
u8 MonCanEnter(u16 si, u16 dx, u8 al)
{
    bool zf;                                    /* the flags of the cmp that the code at MonCanEnter_Test tests */
    bool free_cell = false;
    u16 bx;

    if (MonTile[si] == 4) {                     /* tile 4 (grass) as a creature: only onto its own kind (never happens?) */
        zf = (al == MonTile[si]);
        free_cell = zf;
    } else if (MonTile[si] < 0x40 && MonTile[si] >= 0x2C) {     /* sea creatures: 2Ch-3Fh */
        zf = (al == 0);                         /* water only */
        free_cell = zf;
    } else {                                    /* MonCanEnter_Land */
        if (al == 4 || al == 8 || al == 0x0C || al == 0x20)     /* grass, brush, forest, floor */
            free_cell = true;
    }
    if (!free_cell)
        return 0;                               /* MonCanEnter_No */
    /* MonCanEnter_Free: AL = 0FFh, then is a creature at DX? (BX = slot, or -1) */
    bx = FindMonster(dx & 0xFF, dx >> 8);
    if (bx != 0xFFFF)
        return 0;                               /* a creature stands there */
    return 0xFF;
}

/* asm: MonTurn @226C */
void MonTurn(void)
{
    bool skip = false;                          /* MonTurn_Draw is reached without moving the creatures */
    u16 ax;
    unsigned i;
    bool arrow = false;

    if (PartyTile[0] != 0x3F) {                 /* on foot: the creatures always move */
        ax = Rd(LastKey);                       /* the last command's key word (LastKey) */
        for (i = 0; i < 4; i++)                 /* repne scasw over the four arrow keys */
            if (Rd(&ArrowKeys[i * 2]) == ax) { arrow = true; break; }
        if (!arrow)
            RideToggle = 0xFF;                  /* not an arrow: move this time */
        RideToggle = (u8)-RideToggle;           /* 1 -> -1 -> 1 ...: skip every other step */
        if ((i8)RideToggle < 0)                 /* js */
            skip = true;                        /* MonTurn_Draw: no creature moves */
    }
    if (!skip) {                                /* MonTurn_Clock */
        if (TimeStop != 0) {
            TimeStop--;                         /* Negate Time: frozen */
        } else {
            if (MoveMonsters())                 /* MonTurn_Move: a creature attacked: this frame was dropped, */
                return;                         /* FightCreature never comes back here */
            SpawnMonster();
        }
    }
    BuildView();                                /* MonTurn_Draw */
    ReadCommandNoView();                        /* jmp ReadCommandNoView: the key loop (never comes back) */
}

/* asm: SpawnMonster @22A5 */
void SpawnMonster(void)
{
    u8 dl, al, ah, bl, bh;
    unsigned bx, si;
    u8 *cell;

    if (Location != 0) return;                  /* on Sosaria only */
    dl = Random(0x87);
    if (dl < 0x80) return;                      /* shl dl, 1: carry when DL >= 80h: 7 in 135 */
    for (bx = 0; bx < 0x20; bx++)               /* the first free slot */
        if (MonTile[bx] == 0) break;
    if (bx == 0x20) return;                     /* none: Spawn_Done */
    /* Spawn_Slot */
    al = Random(0x0D);                          /* the kind: rnd(13) AND rnd(13) */
    dl = Random(0x0D);
    dl &= al;
    si = bx;
    bl = dl;
    al = SpawnTiles[bl];                        /* its tile */
    ah = SpawnMoves[bl];                        /* its ground (4 grass, 0 water) */
    MonTile[si] = al;
    MonUnder[si] = ah;                          /* kept as the byte under it */
    dl = Random(0x40);
    if (dl == PlayerXY) goto fail;              /* not in the party's column */
    bl = dl;
    dl = Random(0x40);
    if (dl == PlayerY) goto fail;               /* nor in its row (PlayerY = the party's y) */
    bh = dl;
    MonX[si] = bl;
    MonY[si] = bh;
    MonTalk[si] = 0xC0;                         /* hostile: moves towards the party and attacks */
    al = MapCellAddr(bl, bh, &cell);
    if (al != MonUnder[si]) goto fail;          /* only on its own ground */
    *cell = MonTile[si];                        /* put it on the map */
    return;
fail:
    MonTile[si] = 0;                            /* no place: the slot stays free */
}

/* asm: MonShoot @232F */
void MonShoot(u16 si)
{
    u8 dl, dh, bl, bh, ah, al;
    u8 cl, ch;
    u8 *tile;
    u16 dx;

    dl = Random(0xFF);
    if (dl & 0x80) return;                      /* shl dl, 1 / jb: one time in two */
    {
        u16 step = MonStepToPlayer(si, &dx);    /* CL, CH = the step towards the party (DL, DH are overwritten below) */
        cl = step & 0xFF;
        ch = step >> 8;
    }
    bh = 5;                                     /* BH = view row, BL = view column of the creature */
    bl = 5;
    bh -= PlayerY;
    bh += MonY[si];
    if (bh >= 0x0B) return;
    bl -= PlayerXY;
    bl += MonX[si];
    if (bl >= 0x0B) return;
    BuildView();
    Sound(0xFB);                                /* sound 0FBh */
    dl = bl;                                    /* mov dx, bx */
    dh = bh;
    ah = 3;                                     /* three cells at most */
    for (;;) {                                  /* MonShoot_Step */
        dh += ch;
        if (dh > 0x0B) return;                  /* 0Bh is let through: one past the view (harmless?) */
        dl += cl;
        if (dl > 0x0B) return;
        al = ViewTileAt(dl, dh, &tile);         /* AL = the tile, BX = its place in ViewTiles */
        if (al == 4) return;                    /* mountains */
        if (al == 0x23) return;                 /* wall */
        if (al == 0x24) return;                 /* void */
        *tile = 0x3D;                           /* draw the bolt (Fire) */
        DrawView();
        *tile = al;
        if (dl == 5 && dh == 5) {               /* cmp dx, 505h: the party's cell */
            DamageParty();
            return;
        }
        ah--;
        if (ah == 0) return;
    }
}

/* asm: MoveMonsters @23A5 -- returns true where the assembly drops its own frame and its caller's */
bool MoveMonsters(void)
{
    int si;
    u16 dx = 0, step;
    u8 al, cl = 0, ch = 0, dl, dh;
    u8 *cell;

    for (si = 0x1F; si >= 0; si--) {            /* slot 31 first; MoveMon_Next: dec si / js Done */
        if (MonTile[si] == 0) continue;         /* MoveMon_Skip */
        if (Location == 0) goto chase;          /* on Sosaria all chase the party */
        /* MoveMon_Town: the two high bits of MonTalk say how it moves */
        al = MonTalk[si] & 0xC0;
        al >>= 6;
        if (al == 0) continue;                  /* 0: stands */
        if (al == 1) goto wander;
        if (al == 3) goto chase;                /* 3: hostile */
        step = MonStepToPlayer(si, &dx);        /* 2: approaches (never attacks: MoveMon_Go refuses the party's cell) */
        cl = step & 0xFF;
        ch = step >> 8;
        goto try_step;
    chase:                                      /* MoveMon_Chase: DX = one step towards the party, CL/CH = the step */
        step = MonStepToPlayer(si, &dx);
        cl = step & 0xFF;
        ch = step >> 8;
        if ((dx & 0xFF) == PlayerXY && (dx >> 8) == PlayerY) {  /* cmp dx, word ptr PlayerXY: it steps on the party */
            /* lea sp, [bp+4]: drop the saved registers and the return to MonTurn (this routine's frame
             * and its caller's); then jmp FightCreature with BX = the slot: the fight never comes back */
            FightCreature(si);
            return true;
        }
        goto try_step;
    wander:                                     /* MoveMon_Wander: 1: wanders, half the time */
        dh = 0xFF;
        dl = Random(0xFF);
        if (!(dl & 0x80)) continue;             /* shl dl, 1 / jae: the other half it stays */
        dl = Random(0xFF);
        al = dl;
        cl = (u8)SignStep(&al);                 /* AH = -1, 0 or +1 */
        dl = MonX[si];
        dl += cl;
        dl &= 0x3F;                             /* x 0 is the town's edge: stay */
        if (dl == 0) continue;
        {
            u8 keep = dl;                       /* mov bx, dx ... mov dx, bx: DL (the new x) survives the Random call */
            dl = Random(0xFF);
            al = dl;
            ch = (u8)SignStep(&al);
            dl = keep;
        }
        dh = MonY[si];
        dh += ch;
        dh &= 0x3F;
        if (dh == 0) continue;                  /* y 0 likewise */
        dx = dl | (dh << 8);
    try_step:                                   /* MoveMon_Try: the diagonal step */
        dl = dx & 0xFF;
        dh = dx >> 8;
        al = MapCellAddr(dl, dh, &cell);
        if (MonCanEnter(si, dx, al) == 0xFF) goto go;
        dl = MonX[si];                          /* the vertical step */
        dx = dl | (dh << 8);
        al = MapCellAddr(dl, dh, &cell);
        if (MonCanEnter(si, dx, al) == 0xFF) goto go;
        dl += cl;                               /* the horizontal step */
        dl &= 0x3F;
        dh = MonY[si];
        dx = dl | (dh << 8);
        al = MapCellAddr(dl, dh, &cell);
        if (MonCanEnter(si, dx, al) == 0xFF) goto go;
        if (MonTile[si] == 0x74 || MonTile[si] == 0x3C)         /* cannot move: a dragon or a pirate fires anyway */
            goto shoot;
        continue;
    go:                                         /* MoveMon_Go */
        if (dl == PlayerXY && dh == PlayerY) continue;          /* cmp dx, word ptr PlayerXY: never onto the party */
        MapCellAddr(MonX[si], MonY[si], &cell);
        *cell = MonUnder[si];                   /* the old cell gets back the byte under the creature */
        MonY[si] = dh;
        MonX[si] = dl;
        al = MapCellAddr(dl, dh, &cell);
        MonUnder[si] = al;                      /* remember the byte under the new cell */
        *cell = MonTile[si];                    /* and draw the creature there */
        if (MonTile[si] == 0x74 || MonTile[si] == 0x3C)
            goto shoot;
        continue;
    shoot:                                      /* MoveMon_Shoot */
        MonShoot(si);
    }
    return false;                               /* MoveMon_Done */
}


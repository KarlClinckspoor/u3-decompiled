/* world.c: moons, moon gates, creatures, start-up (src/exodus/WORLD.ASM, 207D-259E).
 *
 * The world turn on the surface and in towns, and the start-up: SaveSosaria / SaveParty write
 * SOSARIA.ULT and PARTY.ULT; AdvanceMoons steps the two moons; Whirlpool takes the frigate to Ambrosia
 * and back; MonTurn (jumped to by MainLoop) is the creatures' turn, then back to the key loop
 * (ReadCommandNoView); StartUp is the program's entry (24C4).
 *
 * StartUp's memory (24C4-2581) is reused once it has run: as ViewTiles (the 11 x 11 view buffer of the
 * library and of BuildView) and as the buffer of the combat maps (docs/FORMATS.md 9). The labels in
 * the middle of its instructions (ViewTiles = StartUp, ViewCell31, ViewCell3B, ViewCell45, and the library's
 * CombatPartyX, CombatPartyY, CombatUnderTile, CombatPartyTile) are places of that buffer that other
 * code reads as data; they are code labels here, not data labels, and have no C of their own: view.c
 * reads the view cells through ViewTiles[n], combat.h gives the combat arrays as offsets into StartUp.
 *
 * Between MoveMonsters and MapWraps the assembly leaves 13 unused zero bytes (24B3-24BF).
 */

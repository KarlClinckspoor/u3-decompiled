/* asm: StartUp @24C4 ignore: StackArea CombatPartyX CombatPartyY CombatUnderTile CombatPartyTile -- SP is not C (the stack is the
 * top of the library's StackArea); the four Combat labels are places inside StartUp's own instructions (see below) */
void StartUp(void)
{
    u16 cx, dx;

    /* lea sp, StackArea / add sp, 100h: SP = the top of the library's 256-byte stack (StackArea + 100h) */
    Wr(&LowMem[0x8C], OFFSET(CtrlBreakHandler));        /* int 23h vector: Ctrl-Break */
    Wr(&LowMem[0x8E], CodeSeg);
    Wr(&LowMem[0x90], OFFSET(CritErrHandler));          /* int 24h vector: critical error */
    Wr(&LowMem[0x92], CodeSeg);
    DrawFrame();
    LoadFile(CharGfx, 0x800, FileCharsetUlt);   /* (the lea dx of this line is ViewCell31, a view cell of BuildView) */
    DrawPlayerNums();
    WindUpdate();                               /* (its call is ViewCell3B) */
    LoadFile(PartyTile, 0x112, FilePartyUlt);   /* (the lea dx is ViewCell45) */
    StatusLine();
    LoadFile(MapBuf, 0x1228, FileSosariaUlt);
    AdvanceMoons();                             /* print the moons (one moon step at each start) */
    LoadFile(TileGfx, 0x1400, FileShapesUlt);
    PlayerXY = PartyXY[0];                      /* the saved position: mov ax, word ptr PartyXY */
    PlayerY = PartyXY[1];
    MapWraps = 0xFF;                            /* the map wraps */
    SoundOn = 0xFF;
    WhirlpoolTick = 1;                          /* the whirlpool's step counter (PARTY 7357) */
    TimeStop = 0;
    LightOn = 0;
    FlushKeys();
    dx = DosGetTime(&cx);                       /* DOS get time: CH hour, CL minutes, DH seconds, DL 1/100 */
    Wr(RandSecHund2, dx);                       /* seed RandState with the time ... */
    Wr(RandSecHund, dx);
    Wr(RandHourMin2, cx);
    /* CombatPartyX, CombatPartyY, CombatUnderTile, CombatPartyTile (library arrays) fall in the next
     * instructions (2564, 2568, 256C, 2570) once a combat map is loaded over this code */
    Wr(RandHourMin, cx);
    dx = DosGetDate(&cx);                       /* DOS get date: CX year, DH month, DL day */
    Wr(RandMonthDay2, dx);                      /* ... and the date */
    Wr(RandMonthDay, dx);
    Wr(RandYear2, cx);
    Wr(RandState, cx);
    ScrollMsg();
    ReadCommand();                              /* BuildView, then the key loop (never comes back) */
}

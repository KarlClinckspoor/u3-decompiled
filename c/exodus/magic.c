/* asm: HitAllMonsters @5EAA
 * Each of the 8 monsters that is alive is hit with a chance of 3 in 4: its cell flashes the magic
 * shape (3Ch, shape 60) and DamageFoe deals AL damage (0FFh: kills). The experience goes to the
 * caster (CombatPlayer's record). */

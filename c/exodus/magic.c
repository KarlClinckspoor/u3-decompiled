/* asm: CastSpell @5D83
 * The Cast command. BX = the caster's record. Chooses the spell list by class (asks "Spell type W/C-"
 * for a druid or ranger), then goes on at Cast_Menu: DI = handler table, SI = menu prompt, DH = 0
 * wizard / 10h cleric (offset into SpellNames). */
void CastSpell(u8 *bx)
{
    u8 al = bx[0x17];                           /* class */
    const Proc *di;
    const u8 *si;
    u8 dh;
    if (al == 0x44 || al == 0x52) {             /* 'D' druid, 'R' ranger: Cast_AskType */
        PrintMsg(MsgSpellType);                 /* "Spell type W/C-" */
        for (;;) {                              /* Cast_TypeKey */
            u16 ax = ReadKeyUpper();            /* AL = key, AH = upper case */
            al = ax & 0xFF;
            u8 ah = ax >> 8;
            di = WizardSpellCmds;
            si = MsgWizardSpell;
            dh = 0;
            if (ah == 0x57)                     /* 'W' */
                break;
            di = ClericSpellCmds;
            si = MsgClericSpell;
            dh = 0x10;
            if (ah == 0x43)                     /* 'C' */
                break;
            if (al == 0x1B) {                   /* Esc: Cast_Esc */
                ScrollMsg();
                Cast_Done();
                return;
            }
            Sound(0xFF);
        }
        PutChar(al);                            /* Cast_EchoType: the key as typed */
    } else {
        di = ClericSpellCmds;
        si = MsgClericSpell;
        dh = 0x10;
        if (al != 0x43 && al != 0x50 && al != 0x49) {       /* 'C' cleric, 'P' paladin, 'I' illusionist */
            di = WizardSpellCmds;
            si = MsgWizardSpell;
            dh = 0;
            if (al != 0x57 && al != 0x4C && al != 0x41) {   /* 'W' wizard, 'L' lark, 'A' alchemist */
                PrintMsg(MsgNotAMage);          /* "Not a mage!" */
                Sound(0xFF);                    /* sound 0FFh: the error beep */
                Cast_Done();
                return;
            }
        }
    }
    Cast_Menu(bx, di, si, dh);                  /* Cast_Menu follows in the assembly */
}

/* asm: Cast_Menu @5DFF
 * The middle of CastSpell: prints the prompt SI, reads a spell letter A-P (Esc leaves), checks and
 * takes the magic points, prints the spell's name and jumps to its handler through the table DI. */
void Cast_Menu(u8 *bx, const Proc *di, const u8 *si, u8 dh)
{
    PrintMsg(si);                               /* "Wizard spell-" / "Cleric spell-" */
    u8 dl;
    for (;;) {                                  /* Cast_SpellKey */
        u16 ax = ReadKeyUpper();                /* AL = key, AH = upper case */
        u8 al = ax & 0xFF;
        u8 ah = ax >> 8;
        if (al == 0x1B) {                       /* Esc: Cast_Esc */
            ScrollMsg();
            Cast_Done();
            return;
        }
        if (ah < 0x41 || ah > 0x50) {           /* not 'A'..'P': Cast_BadKey */
            Sound(0xFF);
            continue;
        }
        PutChar(al);
        ScrollMsg();
        dl = ah - 0x41;                         /* the spell index 0-15 */
        break;
    }
    /* Cast_Spell */
    u8 cost = ToBcd(dl * 5);                    /* mul ah (5) / aam / shl ah, 4 / or: the cost, BCD (A 0 ... P 75) */
    if (cost > bx[0x19]) {                      /* magic points (BCD) */
        Cast_MPLow();
        return;
    }
    bool cf = false;
    bx[0x19] = SubDas(bx[0x19], cost, &cf);     /* xchg [bx+19h], al / sub al, [bx+19h] / das: points -= cost */
    ScrollMsg();
    const u8 *name = SpellNames[dl + dh];       /* the spell's name */
    Proc handler = di[dl];                      /* add di, 2 * index */
    PrintMsg(name);
    ScrollMsg();
    ScrollMsg();
    handler(bx, dl);                            /* jmp word ptr [di]: to the handler, which ends at Cast_Done / Cast_Failed */
}


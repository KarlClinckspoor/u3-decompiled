/* The CGA stand-in: one word of the screen xor 0FFFFh (`xor word ptr [bx], 0FFFFh` with DS = B800). */
static void XorScreenWord(unsigned bx)
{
    CgaMem[bx] ^= 0xFF;
    CgaMem[bx + 1] ^= 0xFF;
}

/* asm: SaveGame @6B91 */
void SaveGame(void)
{
    u8 al;
    if (Location == 0)                          /* je SaveGame_WithMap */
        goto WithMap;
    if (Location != 0x80)                       /* 80h: a fight */
        goto PartyOnly;
    if (SavedLocation == 0)
        goto WithMap;
PartyOnly:
    al = Location;
    Location = 0;                               /* the saved party always says "Sosaria" */
    SaveParty();
    Location = al;
    return;
WithMap:
    al = Location;
    Location = 0;
    SaveSosaria();
    Location = al;
}

/* asm: HurtPlayer @6BC9 */
u8 HurtPlayer(u8 al, u8 *bx)
{
    u8 cl, ch, lo, hi;
    bool cf = false;

    cl = al;
    lo = bx[0x1A];                              /* hit points (BCD word) */
    hi = bx[0x1B];
    lo = SubDas(lo, cl, &cf);                   /* sub al, cl; das */
    hi = SubDas(hi, 0, &cf);                    /* xchg al, ah; sbb al, 0; das; xchg al, ah */
    bx[0x1A] = lo;
    bx[0x1B] = hi;
    ch = 0;
    if (cf) {                                   /* jae HurtPlayer_Status not taken: below zero */
        bx[0x11] = 0x44;                        /* status 'D' dead */
        bx[0x1A] = 0;
        bx[0x1B] = 0;
        SaveGame();
        ch = 0xFF;
    }
    StatusLine();
    return ch;                                  /* AL = 0FFh if the player died, else 0 */
    /* the assembly has a stray `ret` (0C3h) after this routine that nothing reaches */
}

/* asm: PrintName @6BFA */

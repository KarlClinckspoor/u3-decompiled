/* asm: CheckTerrain @7254 */
u8 CheckTerrain(u8 al)
{
    u8 cl_, ah;
    u8 *bx;
    u16 cx;
    int i;

    if (PartyTile[0] == 0x0B) {                 /* frigate: water and whirlpools only */
        if (al == 0)                            /* water */
            return 0;
        if (al == 0x0C)                         /* whirlpool */
            return 0;
        return 0xFF;
    }
    /* CheckTerrain_Land */
    if (al == 0x20)                             /* force field */
        goto Force;
    if (al == 0x21)                             /* lava (via CheckTerrain_ToLava, a short jump) */
        goto Lava;
    if (al == 0x22)                             /* moon gate */
        goto Step;
    if (al == 0x3E)                             /* shrine */
        goto Step;
    if (al >= 0x0C)                             /* whirlpool and up: creatures, walls ... */
        return 0xFF;
    if (al == 0)                                /* water */
        return 0xFF;
    if (al == 4)                                /* mountains */
        return 0xFF;
Step:
    Sound(0xF6);                                /* step sound */
    for (cx = 0x2000; cx != 0; cx--)            /* loop CheckTerrain_Wait1: delay (CPU speed dependent) */
        ;
    Sound(0xF6);                                /* AL is still 0F6h (Sound saves AX) */
    if (PartyTile[0] == 0x0A) {                 /* horse: a third hoof beat */
        for (cx = 0x2000; cx != 0; cx--)
            ;
        Sound(0xF6);
    }
    return 0;                                   /* CheckTerrain_Ok */

Force:
    FlashView();                                /* flash the map window */
    SoundBX = (SoundBX & 0xFF00) | 0x10;        /* BL = 10h, its length (SndNoise reads BL; BH is left as it was) */
    Sound(0xFC);                                /* the header says: a buzz (?) */
    cl_ = PartySize;
    bx = Players;
    for (i = 0; i < cl_; i++) {                 /* CL counts PartySize down: i = PartySize - CL = the player 0-3 */
        if ((bx[0x0E] & 0x10) == 0) {           /* no Mark of Force */
            HurtPlayer(0x99, bx);               /* 99 hit points (dead or not: no IsUp test) */
            FlashPlayer(i);                     /* AL = PartySize - CL */
            ah = i;
            Sound(0xF7);                        /* hit sound */
            FlashPlayer(ah);
            FlashView();
            StatusLine();
            return 0xFF;                        /* jmp CheckTerrain_No: only the first player without the Mark burns */
        }
        bx += 0x40;
    }
    FlashView();                                /* all have the Mark of Force: they pass */
    goto Step;

Lava:
    Sound(0xF8);                                /* the lava sound (?) */
    bx = Players;
    cl_ = PartySize;
    for (i = 0; i < cl_; i++) {
        if (IsUp(bx) && (bx[0x0E] & 0x20) == 0) {       /* up, and no Mark of Fire */
            HurtPlayer(0x50, bx);               /* 50 hit points */
            FlashPlayer(i);
            ah = i;
            Sound(0xF7);
            FlashPlayer(ah);
        }
        bx += 0x40;
    }
    StatusLine();
    return 0;                                   /* lets the party pass, without the step sounds */
}

/* asm: MoveWhirlpool @7347 */
u8 MoveWhirlpool(u8 bl)
{
    u8 dl, al, cl, ch, dh;
    u8 *cell;
    u8 *old;
    u8 newbl = bl;

    if (Location != 0)                          /* Sosaria */
        return bl;
    WhirlpoolTick--;
    if (WhirlpoolTick != 0)                     /* jne MoveWhirlpool_Exit */
        return bl;
    WhirlpoolTick = 4;
    dl = Random(8);
    if (dl == 0)                                /* 1 in 8: turn */
        goto Turn;
    cl = WhirlpoolX;                            /* mov cx, word ptr WhirlpoolX: the whirlpool's x, y */
    ch = WhirlpoolY;
    ch += WhirlpoolDY;
    cl += WhirlpoolDX;
    cl &= 0x3F;                                 /* and cx, 3F3Fh: the map wraps at 64 */
    ch &= 0x3F;
    al = MapCellAddr(cl, ch, &cell);
    if (al == 0)                                /* water */
        goto Move;
    if (al != 0x2C)                             /* a frigate (shape 0Bh) */
        goto Turn;
    *cell = 0x30;                               /* whirlpool (shape 0Ch) */
    MapCellAddr(WhirlpoolX, WhirlpoolY, &old);  /* mov bx, word ptr WhirlpoolX; ... call MapCellAddr */
    WhirlpoolX = cl;                            /* mov word ptr WhirlpoolX, cx */
    WhirlpoolY = ch;
    *old = 0;                                   /* water where it was */
    if (cl == PlayerXY && ch == PlayerY)        /* cmp cx, word ptr PlayerXY */
        goto Hit;
    BuildView();
    Sound(0xF4);
    PrintMsg(MsgShipDestroyed);                 /* "A ship was Destroyed!" */
    return bl;

Turn:
    dl = Random(8);
    WhirlpoolDX = WhirlDxTbl[dl];
    WhirlpoolDY = WhirlDyTbl[dl];
    goto Check;

Move:
    *cell = 0x30;                               /* whirlpool */
    MapCellAddr(WhirlpoolX, WhirlpoolY, &old);
    WhirlpoolX = cl;
    WhirlpoolY = ch;
    *old = 0;                                   /* water */
    BuildView();
Check:
    if (WhirlpoolX != PlayerXY || WhirlpoolY != PlayerY)        /* cmp ax, word ptr PlayerXY */
        return bl;
Hit:
    Whirlpool();                                /* the whirlpool takes the party */
    PutChar(0x10);                              /* the prompt character, as in the main loop */
    /* pop bx (the caller's BX); mov ah, 2Ch; int 15h. The main loop gets the time with int 21h; here it
     * is int 15h, which is no DOS call (BUG, as in the original: meant int 21h). DH is not set by
     * it: as far as the assembly shows, DH is still 8 (mov dh, 8 before the calls to Random, which
     * keep DH; Whirlpool and PutChar save all), if the BIOS leaves it alone. */
    dh = 8;
    newbl = dh + 5;                             /* "seconds + 5, mod 60" */
    if (newbl >= 0x3C)
        newbl -= 0x3C;
    return newbl;                               /* BL renewed */
}

/* asm: UpcaseBuf @740A */
void UpcaseBuf(u8 *di, u16 cx)
{
    if (cx == 0)                                /* jcxz UpcaseBuf_Done */
        return;
    do {
        if (*di >= 0x61 && *di <= 0x7A)         /* 'a'-'z' */
            *di += 0xE0;                        /* - 20h */
        di++;
        cx--;
    } while (cx != 0);
}

/* asm: MatchWord @7423 */
u8 MatchWord(const u8 *si, const u8 *di, u16 cx)
{
    if (cx == 0)                                /* jcxz MatchWord_No */
        return 0;
    for (;;) {                                  /* MatchWord_Skip: leading spaces */
        if (*di != 0x20)
            break;
        di++;
        cx--;
        if (cx == 0)
            return 0;                           /* only spaces */
    }
    for (;;) {                                  /* MatchWord_Cmp */
        if (*si != *di)
            return 0;
        if (si[1] == 0x20)                      /* the word ends here: only spaces may follow */
            break;
        si++;
        di++;
        cx--;
        if (cx == 0)
            return 0;                           /* typed text shorter than the word */
    }
    for (;;) {                                  /* MatchWord_TailNext / MatchWord_Tail */
        di++;
        cx--;
        if (cx == 0)
            return 0xFF;                        /* a match */
        if (*di != 0x20)                        /* MatchWord_Tail: trailing spaces only */
            return 0;
    }
}

/* party.c: names, status lines, hit points, food, poison (src/exodus/PARTY.ASM, 6B91-7458).
 *
 * The routines that work on the four player records (Players, 64 bytes each, docs/FORMATS.md 6):
 * saving the game (SaveGame), damage and death (HurtPlayer), PrintName, IsUp, the "All Players
 * Out!" check (CheckAllOut), AskPlayer, the four status boxes on the right (StatusLine,
 * DrawPlayerNums), the Ztats screen (ShowZtats), the per-turn upkeep (PartyUpkeep: magic points
 * by class, food, poison, hit point regeneration), the screen inversions used as "flashes"
 * everywhere (FlashPlayer a status box, FlashView the map window, InvertPlayerNum a player
 * number), the checks before a move (AgainstWind, CheckTerrain), the whirlpool (MoveWhirlpool)
 * and two helpers for typed words (UpcaseBuf, MatchWord).
 *
 * A record is a `u8 *` and its fields are read at their byte offsets as the assembly does
 * (docs/FORMATS.md 6: 0Eh marks and cards, 11h status, 12h-15h Str Dex Int Wis, 16h race, 17h
 * class, 18h sex, 19h magic points, 1Ah-1Bh hit points, 1Ch-1Dh maximum, 1Eh-1Fh experience,
 * 20h-22h food, 23h-24h gold, 25h gems, 26h keys, 27h powders, 28h-2Fh armours, 30h-3Fh weapons).
 * Numbers in the records are BCD; the `add/sub` + `daa/das` of the assembly are AddDaa / SubDas
 * (bcd.h), which give the carry the assembly tests afterwards.
 *
 * The flashes write the CGA memory directly through the segment kept at ds:[4F39h] (the lib's
 * ScreenSeg, B800): in the C that is CgaMem (u3.h), even scan lines at 0000, odd ones at 2000h.
 */

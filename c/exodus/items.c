/* asm: ReadKeyUpper @5D16
 * ReadKey; returns AX: AL = the key, AH = the key with a-z made upper case. */
u16 ReadKeyUpper(void)
{
    u8 al = ReadKey() & 0xFF;
    u8 ah = al;
    if (ah >= 0x61 && ah <= 0x7A)               /* 'a'..'z' */
        ah += 0xE0;                             /* - 20h */
    return al | (ah << 8);
}

/* asm: AddHitPoints @5D2B
 * Adds AL (BCD) to the hit points (a BCD word at 1Ah) of the record at BX, at most its maximum (1Ch).
 * The carry out of the high byte is not tested: a sum past 9999 wraps (and then stays below the maximum). */
void AddHitPoints(u8 al, u8 *bx)
{
    bool cf = false;
    bx[0x1A] = AddDaa(al, bx[0x1A], &cf);       /* add al, [bx+1Ah] / daa */
    bx[0x1B] = AddDaa(bx[0x1B], 0, &cf);        /* adc al, 0 / daa */
    u16 max = Rd(bx + 0x1C);                    /* maximum hit points */
    if (max < Rd(bx + 0x1A))                    /* cmp ax, [bx+1Ah] / jae: more than the maximum */
        Wr(bx + 0x1A, max);
}


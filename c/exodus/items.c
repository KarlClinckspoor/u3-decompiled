/* asm: DexRoll @5B85
 * A roll against the dexterity of the player at BX: success (ZF set) when Random(255) < Dex + bonus,
 * the bonus 128 for a thief, 64 for a barbarian, illusionist or ranger, else 0. All in 8 bits. */
bool DexRoll(const u8 *bx)
{
    u8 dex = bx[0x13];                          /* dexterity (BCD) */
    u8 al = (u8)((dex >> 4) * 10 + (dex & 0x0F));   /* shl ax, 4 / and al, 0Fh / aad: the binary value */
    al += 0x40;
    if (bx[0x17] == 'B' || bx[0x17] == 'I' || bx[0x17] == 'R') {    /* barbarian, illusionist, ranger: +64 */
    } else {
        al += 0x40;
        if (bx[0x17] != 'T')                    /* thief: +128 */
            al -= 0x80;                         /* the others: no bonus */
    }
    u8 dl = Random(0xFF);                       /* DL = 0..DH-1 */
    return dl < al;                             /* cmp dl, al / jae: success (AL = 0, ZF set) when below */
}


/* asm: CmdFire @5BCF
 * F: fire the frigate's cannons in a direction: three cells, each flashing fire (map byte 0F4h,
 * shape 61); the first creature in the line is hit with a chance of 1/2 (a pirate ship, 3Ch, 1/4),
 * and "<name>s Destroyed!" removes it. */
void CmdFire(const u8 *si)
{
    PrintMsg(si);
    if (PartyTile[0] != 0x0B) {                 /* 0Bh: on a frigate */
        MsgWhat();
        return;
    }
    /* Fire_OnShip */
    PrintMsg(MsgFireDirect);
    u16 dx, bx;
    if (AskDirection(&dx, &bx))                 /* ZF: Esc */
        return;                                 /* Fire_Done */
    Sound(0xFB);                                /* the cannon */
    u8 cl = PlayerXY, ch = PlayerY;             /* mov cx, word ptr PlayerXY */
    u8 stepx = dx & 0xFF, stepy = dx >> 8;      /* mov ax, dx: AL, AH = the step */
    for (u16 si_range = 3; si_range != 0; si_range--) {         /* SI = 3: range 3 cells */
        ch += stepy;                            /* Fire_Step */
        cl += stepx;
        cl &= 0x3F; ch &= 0x3F;                 /* and cx, 3F3Fh */
        dx = cl | (ch << 8);
        bx = FindMonster(dx & 0xFF, dx >> 8);   /* BX = the creature's slot or -1 */
        if (bx != 0xFFFF) {                     /* Fire_Hit */
            u16 di = bx;
            u8 *cell;                           /* BX = its map cell, AL = its byte */
            u8 under = MapCellAddr(dx & 0xFF, dx >> 8, &cell);
            *cell = 0xF4;                       /* fire on the map */
            BuildView();
            Sound(0xF7);
            if (MonTile[di] == 0x3C) {          /* 3Ch: pirate ship (shape 15): first roll, 1 in 2 */
                u8 dl = Random(0xFF);
                if (!(dl & 0x80)) {             /* shl dl, 1 / jae: bit 7 clear = miss */
                    *cell = under;              /* Fire_Miss: put the cell back, Fire_Redraw */
                    BuildView();
                    return;
                }
            }
            u8 dl = Random(0xFF);               /* Fire_Roll: 1 in 2 (the ship: 1 in 4 over both rolls) */
            if (!(dl & 0x80)) {                 /* Fire_Miss */
                *cell = under;
                BuildView();                    /* Fire_Redraw */
                return;
            }
            PrintName((MonTile[di] >> 2) + 1);  /* shape + 1 = name number */
            PrintMsg(MsgDestroyed);
            *cell = MonUnder[di];               /* the map byte under the creature */
            MonTile[di] = 0;                    /* the slot is free */
            return;                             /* Fire_Done */
        }
        u8 *cell;                               /* push ax / mov bx, dx / call MapCellAddr */
        u8 al = MapCellAddr(dx & 0xFF, dx >> 8, &cell);     /* AL = the cell's byte */
        *cell = 0xF4;                           /* fire on the map */
        BuildView();
        *cell = al;                             /* put the cell back; pop ax: the step is back */
    }
    BuildView();                                /* Fire_Redraw */
}

/* asm: CmdJoinGold @5C73
 * J: give the whole party's gold to one player. The sum is BCD; past 9999 it is "No more room!"
 * and nothing changes. All four slots' gold is cleared, even past PartySize (only PartySize
 * slots are added up). */
void CmdJoinGold(const u8 *si)
{
    PrintMsg(si);
    u8 *bx;
    if (AskPlayer(&bx) == 0)                    /* ZF: nobody */
        return;                                 /* Join_Done */
    u8 *di = bx;                                /* DI = the receiver */
    u8 *first = Players;                        /* SI = the first record */
    bx = Players;
    u16 cx = PartySize;
    u16 ax = 0;
    do {                                        /* Join_Sum: a BCD word */
        u16 dx = Rd(bx + 0x23);                 /* gold */
        bool cf = false;
        u8 al = AddDaa(ax & 0xFF, dx & 0xFF, &cf);      /* add al, dl / daa */
        u8 ah = AddDaa(ax >> 8, dx >> 8, &cf);          /* xchg al, ah / adc al, dh / daa / xchg al, ah */
        ax = al | (ah << 8);
        if (cf) {                               /* jb Join_TooMuch */
            PrintMsg(MsgNoMoreRoom);
            Sound(0xFF);
            return;
        }
        bx += 0x40;
    } while (--cx != 0);                        /* loop (CX = PartySize, never 0) */
    bx = first;
    for (cx = 4; cx != 0; cx--) {               /* Join_Clear: all four slots */
        Wr(bx + 0x23, 0);
        bx += 0x40;
    }
    Wr(di + 0x23, ax);
}


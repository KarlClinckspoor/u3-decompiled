static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }
static void Wr(u8 *p, u16 w) { p[0] = w & 0xFF; p[1] = w >> 8; }

/* asm: InExodusCastle @5B28
 * Returns ZF (true = set, AL = 0FFh): Location 3 (a castle), or a fight (80h) that started in
 * one (SavedLocation 3), and the party's x is the one of the castle's entrance. Only x is compared. */
bool InExodusCastle(void)
{
    if (Location == 0x80) {                     /* a fight */
        if (SavedLocation != 3)                 /* InExodus_Combat */
            return false;                       /* InExodus_No: AL = 0 */
    } else if (Location != 3)                   /* 3: a castle */
        return false;
    /* InExodus_CheckX */
    if (PartyXY[0] != ExodusCastleX[0])         /* the x of EXODUS.ULT's entrance */
        return false;
    return true;                                /* AL = 0FFh */
}


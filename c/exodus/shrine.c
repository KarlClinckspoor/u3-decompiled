/* asm: PrintLevelHead @62FD ignore: CursorCol -- GetCursor/SetCursor are the word access to CursorCol, CursorRow */
void PrintLevelHead(void)
{
    u16 cursor = GetCursor();                   /* push word ptr CursorCol (popped at the end) */
    PrintAt(0x0009, MsgLvl);                    /* DL = 9, DH = 0: column 9 of row 0 (the header's "?") */
    PutChar(DungeonLevel + 0x31);               /* '1'-'8' */
    PrintAt(0x1707, MsgHead);                   /* column 7, row 17h */
    PrintStr(FacingNames[Facing]);              /* Facing 0-3: bx = Facing * 2 into the word table */
    SetCursor(cursor);
}

/* asm: MonStepToPlayer @633B */
u16 MonStepToPlayer(u16 si, u16 *dx)
{
    u8 al, cl, ch, dl, dh;
    al = PlayerXY;                              /* the party's x */
    dl = MonX[si];
    al = al - dl;
    cl = SignStep(&al);                         /* AH = -1, 0, +1 */
    dl += cl;
    dl &= 0x3F;
    al = PlayerY;                               /* PlayerY = the party's y */
    dh = MonY[si];
    al = al - dh;
    ch = SignStep(&al);
    dh += ch;
    dh &= 0x3F;
    *dx = dl | (dh << 8);
    return cl | (ch << 8);
}

/* asm: EnterShrine @6366 */
void EnterShrine(void)
{
    u8 *bx;                                     /* the player's record (from AskPlayer) */
    u8 al, cl, ah;
    u16 bp;                                     /* BP = AX after `dec al`: AL = the slot 0-3 (AH is unused) */
    u16 di, dx;
    int race;
    bool carry;

    PrintMsg(MsgShrineWho);
    al = AskPlayer(&bx);
    if (al == 0)                                /* jne Shrine_Chosen */
        goto Shrine_Done;
    al--;                                       /* AL = slot 0-3 */
    bp = al;
    if (!IsUp(bx))                              /* ZF set: good or poisoned */
        goto Shrine_Incap;

    /* Shrine_Enter: load SHRINE.IMG into the view buffer (lea bx, StartUp: the start-up code at
     * 24C4, which the game reuses as ViewTiles once it has run) */
    LoadFile(ViewTiles, 0x79, FileShrineImg);
    DrawView();
    Location = 4;                               /* 4: a shrine */
    PrintMsg(MsgWelcomeShrine);
    al = PlayerXY & 3;                          /* the shrine's stat: the party's x & 3 */
    dx = al;                                    /* DX = DI = the stat 0-3 */
    PrintMsg(ShrineStatNames[dx]);  /* the table of words: si = dx * 2 */

    /* the race's index: repne scasb over RaceLetters (5 bytes); not found leaves CX = 0, DI = 4 */
    al = bx[0x16];                              /* race letter */
    race = 4;
    for (int k = 0; k < 5; k++) {
        if (RaceLetters[k] == al) {
            race = k;
            break;
        }
    }
    cl = RaceStatMax[dx + race * 4];            /* CL = the stat's maximum (4 stats per race) */
    di = dx;                                    /* DI = the stat (0-3) */
    PrintMsg(MsgOffering);
    al = ReadNumber() & 0xFF;                   /* AL = the offering (BCD, in hundreds) */
    if (al == 0)
        goto Shrine_NoOffer;
    if (al > bx[0x24])                          /* gold in hundreds (BCD) */
        goto Shrine_Cheat;
    ah = al;                                    /* AH = the offering */
    /* mov ah, [bx+24h]; xchg al, ah; sub al, ah; das: gold - offering, never below 0 (ja above) */
    bx[0x24] = ToBcd(BcdVal(bx[0x24]) - BcdVal(ah));    /* pay */
    al = bx[di + 0x12];                         /* the stat (record 12h-15h) */
    {
        unsigned sum = BcdVal(al) + BcdVal(ah); /* add al, ah; daa */
        carry = sum > 99;
        al = ToBcd(sum % 100);
    }
    if (carry || al > cl)                       /* jb Shrine_Cap; cmp al, cl; jbe Shrine_Store */
        al = cl;                                /* Shrine_Cap: at most the race's maximum; gold paid beyond is lost */
    bx[di + 0x12] = al;                         /* Shrine_Store */
    PrintMsg(MsgShazam);
    FlashPlayer(bp);
    FlashView();
    SoundBX = 0x30D8;                           /* BL = 0D8h, BH = 30h */
    Sound(0xFD);
    FlashView();
    FlashPlayer(bp);
Shrine_Done:
    Location = 0xFF;                            /* Ambrosia */
    return;

Shrine_Cheat:
    PrintMsg(MsgCantCheat);
    Sound(0xFF);
    goto Shrine_Done;

Shrine_NoOffer:
    PrintMsg(MsgThenBeOff);
    goto Shrine_Done;

Shrine_Incap:
    PrintMsg(TxtIncapacitated);                 /* "Incapacitated!" */
    Sound(0xFF);
    goto Shrine_Done;
}


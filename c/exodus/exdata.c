/* ---- ReadCommand ---- */

static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }      /* a word of a byte table: low byte first */

/* asm: ReadCommand @1B77 */
void ReadCommand(void)
{
    BuildView();                                /* draw the view ... */
    ReadCommandNoView();                        /* ... and fall into the key loop */
}

/* asm: ReadCommandNoView @1B7A */
void ReadCommandNoView(void)
{
    u16 ax, cx, dx;
    u8 bl;

    CheckAllOut();                              /* is anyone still up? (else the game stops) */
    PutChar(0x10);                              /* prompt character 10h */
    dx = DosGetTime(&cx);                       /* DOS: get time, DH = seconds */
    bl = (u8)((dx >> 8) + 5);                   /* wait until 5 seconds later */
    if (bl >= 0x3C) bl -= 0x3C;                 /* seconds wrap at 60 */
    for (;;) {                                  /* ReadCommand_Wait */
        bl = MoveWhirlpool(bl);                 /* the whirlpool moves every 4th pass (BL = the deadline, may be renewed) */
        if (KeyReady()) {                       /* ZF clear: a key waits */
            ax = ReadKey();                     /* ReadCommand_Key */
            u8 al = ax & 0xFF;
            if (al >= 0x61 && al <= 0x7A)       /* lower case to upper */
                ax = (ax & 0xFF00) | (u8)(al - 0x20);
            break;
        }
        dx = DosGetTime(&cx);                   /* DOS: get time */
        if (bl == (dx >> 8)) {                  /* the deadline: no key */
            ax = 0x3920;                        /* Space (Pass) */
            break;
        }
    }

    /* ReadCommand_Find: repne scasw over the 33 key words of SurfaceKeys (first match wins; the words are
     * scan code << 8 | character, stored low byte first) */
    unsigned bx;                                /* BX = index * 2 in the assembly; here the index */
    for (bx = 0; bx < 0x21; bx++)
        if (Rd(&SurfaceKeys[bx * 2]) == ax) break;
    if (bx == 0x21) {                           /* not a command */
        MsgWhat();                              /* jmp MsgWhat: "What?", and the turn ends */
        MainLoop();                             /* (the shared exit's jmp MainLoop: see below) */
        return;
    }
    const u8 *si = SurfacePrompts[bx];          /* SI = the prompt */
    LastKey[0] = ax & 0xFF;                     /* LastKey: the command's key word (MonTurn reads it) */
    LastKey[1] = ax >> 8;
    /* jmp word ptr SurfaceCmds[bx]: the handler is entered with SI = its prompt (it prints it first); BX = the
     * index * 2 and AX = the key word are still in the registers, which no handler reads. The handlers end
     * with `jmp MainLoop`; in the C they return here, and the dispatcher runs the turn: MainLoop ends in
     * MonTurn, which comes back to ReadCommandNoView (the key loop closes here, as a chain of calls). */
    ((void (*)(const u8 *))SurfaceCmds[bx])(si);
    MainLoop();
}

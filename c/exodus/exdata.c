/* exdata.c: EXODUS's data and the top of the surface turn (src/exodus/EXDATA.ASM, 0100-1BD5).
 *
 * The data at the start of EXODUS.BIN, used by every other module (all of it is generated below,
 * and declared for the others in exodus_data.h; see c/exodus/types.txt for how the buffers are cut):
 *  - MapBuf (0100-1326): the map file as loaded, with the speeches (MapText), the 32 creature slots
 *    (MonTile ... MonTalk), the whirlpool and the moons inside it; in a dungeon DUNGEON.DAT and the
 *    dungeon file (DungeonMap). Entry vector: `dw StartUp` at 1328, which has no label, so it has no
 *    C (BOOTUP jumps through it);
 *  - ScreenRowTbl (132A): the screen offset of each scan line;
 *  - PartyTile (14BA-15CB): PARTY.ULT as loaded, the 18-byte header and the four 64-byte records
 *    (Players ...), then the variables (PlayerXY, PlayerY, LightOn, DungeonLevel, ...) and file names;
 *  - the surface command table (SurfaceKeys, SurfacePrompts, SurfaceCmds), the moon gates, the creature
 *    spawning tables and the strings of the surface commands (LOOP, WORLD);
 *  - 1B77-1BD4: code, ReadCommand: the top of the surface turn (it continues in LOOP: MainLoop).
 *
 * Not C: the labels in the PSP (Ofs80h, CmbMonY, CmbMonUnder, CmbMonHP, CmbPlrX, CmbPlrY, CmbPlrUnder,
 * CmbPlrTile: ORG 80h ... 0ACh) are no storage, only offsets into the combat area at StartUp that
 * COMBAT adds to a register (combat.h gives them as constants).
 */

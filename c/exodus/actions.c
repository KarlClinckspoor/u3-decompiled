/* asm: CmdInsert @762F */
void CmdInsert(u8 *di, u16 bp)
{
    u16 dx, bx16;
    u8 *si;                                     /* the map cell (kept on the stack across the menu) */
    u8 al, ah, cl, ch;
    u16 cards;
    int i;

    PrintMsg(MsgOtherDirect);                   /* "Direct? " */
    if (AskDirection(&dx, &bx16))               /* jne CmdInsert_Cell; else Done: Esc */
        return;
    cl = bx16 & 0xFF;                           /* CL = the target's x */
    al = MapCellAddr(bx16 & 0xFF, bx16 >> 8, &si);
    if (al != 0x7C)                             /* Exodus (shape 31) */
        goto NoEffect;
    PrintMsg(MsgCardMenu);                      /* "D, S, L, M:" */
    al = AskChoice(6, CardKeys, CardNames);     /* the card names; keys M D L S Q Esc */
    ScrollMsg();
    if (al == 0x51)                             /* 'Q' */
        return;
    if (al == 0x1B)                             /* Esc */
        return;
    /* CardsInserted is a word in the assembly (mov bx, word ptr CardsInserted; inc word ptr ...);
     * the data generator made it two bytes (db 0, 0), so the C reads and writes it as two. */
    cards = CardsInserted[0] | (CardsInserted[1] << 8);     /* BX = the cards in so far */
    ch = cl;                                    /* CH = the target's x */
    ah = 1;
    cl = cards & 0xFF;
    ah <<= cl;                                  /* the bit of card n */
    if ((di[0x0E] & ah) == 0)                   /* owns card bit n? */
        goto NoEffect;
    ah = (cards & 0xFF) + 0x1E;
    if (ah != ch)                               /* x = 1Eh + n? */
        goto Wrong;
    if (al != CardOrder[cards])                 /* "LSMD"[n]? */
        goto Wrong;
    cards++;                                    /* inc word ptr CardsInserted */
    CardsInserted[0] = cards & 0xFF;
    CardsInserted[1] = cards >> 8;
    for (i = 0; i < 5; i++) {                   /* mov cx, 5 ... loop CmdInsert_Flash */
        *si = 0xF0;                             /* shape 60 (Magic) */
        BuildView();
        Sound(0xF7);
        *si = 0x7C;                             /* Exodus */
        BuildView();
        Sound(0xF7);
    }
    *si = 0x20;                                 /* floor (shape 8) */
    BuildView();
    if (cards != 4)                             /* cmp word ptr CardsInserted, 4 */
        return;
    EndGame();                                  /* all four: the ending (jmp EndGame; never returns) */
    return;

NoEffect:
    PrintMsg(MsgNoEffect);                      /* "No effect!" */
    return;

Wrong:                                          /* wrong place or card: the player dies */
    FlashPlayer(bp);                            /* mov ax, bp: AL = the player 0-3 */
    Sound(0xF7);
    FlashPlayer(bp);
    di[0x1A] = 0;                               /* hit points 0 ... */
    di[0x1B] = 0;
    HurtPlayer(0xFF, di);                       /* ... minus 0FFh: dead */
}

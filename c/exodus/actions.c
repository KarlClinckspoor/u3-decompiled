/* asm: CmdBribe @75A9 */
void CmdBribe(u8 *di)
{
    u16 dx, bx;
    u8 *cell;
    u8 al, ah, dl, dh;
    bool cf;

    PrintMsg(MsgOtherDirect);                   /* "Direct? " */
    if (AskDirection(&dx, &bx))                 /* je CmdBribe_Done: Esc */
        return;
    dx = bx;                                    /* DL, DH = the target's x, y */
    bx = FindMonster(dx & 0xFF, dx >> 8);
    if (bx == 0xFFFF)                           /* cmp bx, -1 */
        goto NoEffect;
    if (MonTile[bx] != 0x48)                    /* a guard */
        goto NoEffect;
    /* mov ax, word ptr [di+23h]; xchg al, ah; sub al, 1; das: 1 off the high BCD byte = 100 gold */
    cf = false;
    al = SubDas(di[0x24], 1, &cf);
    if (cf)                                     /* jb CmdBribe_NoGold */
        goto NoGold;
    di[0x24] = al;                              /* the low byte (23h) is unchanged */
    ah = MonUnder[bx];
    dh = MonY[bx];
    dl = MonX[bx];
    MonTile[bx] = 0;                            /* the slot is free */
    MapCellAddr(dl, dh, &cell);
    *cell = ah;                                 /* the map cell gets MonUnder's byte back */
    return;

NoEffect:
    PrintMsg(MsgNoEffect);                      /* "No effect!" */
    return;

NoGold:
    PrintMsg(MsgNotEnoughGold);                 /* "Not enough gold!" */
    Sound(0xFF);
}


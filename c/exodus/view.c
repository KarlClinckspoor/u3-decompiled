/* view.c: the map window and map access (src/exodus/VIEW.ASM, 259E-298E).
 *
 * The screen layout and the map window. Text cells are 8 x 8 pixels (40 x 25); the map window is cells
 * 1-22 of rows 1-22 (11 x 11 tiles of 16 x 16 pixels), the message window rows 11h-17h, columns
 * 18h-27h. BuildView fills the 11 x 11 view buffer (ViewTiles, the memory of StartUp: see world.c) around
 * the party, hides what forests, mountains and walls block and draws it; it also leaves the shapes of
 * the party's cell and its four neighbours in TileEast, TileWest, TileNorth, TileSouth and TileHere
 * (WORLD), which the movement and Enter commands read. PrintMsg prints a string in the message window.
 * MapCellAddr / DungeonCell give the address and byte of a map cell. ShowGemMap and ShowDungeonMap are
 * the "Peer at gem" maps.
 */
#include "../u3.h"
#include "../lib/lib.h"
#include "exodus_data.h"
#include "view.h"

extern u8 ViewTiles[];                      /* the 11 x 11 view buffer = StartUp's memory (lib.c, world.c) */


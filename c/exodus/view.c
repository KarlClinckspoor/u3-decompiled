void BiosScrollUp(u8 al, u8 bh, u8 ch, u8 cl, u8 dh, u8 dl);   /* int 10h AH=6: scroll the window CH,CL - DH,DL (row, column)
                                                                  up AL lines (0 = clear it), the new lines in attribute BH */


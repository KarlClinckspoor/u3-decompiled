/* intro.c: INTRO.ASM, ULTIMA.COM: the title animation, sound and the chain load of BOOTUP.BIN.
 *
 * ULTIMA.COM is the intro. StartUp installs Ctrl-Break and critical-error handlers, checks for a
 * CGA and sets mode 4 (SetGraphicsMode), seeds the library's random generator from the clock,
 * copies BLANK.IBM (the frame, the ground, the party and the dragon) to the screen and loads
 * EXOD.IBM into PictureBuf, NAME.DAT and ANIMATE.DAT. It then builds the title from pieces of
 * EXOD.IBM: "Exodus" and "Ultima III" dissolve in with static (CopyPicture), "by", the "Lord
 * British" signature is written point by point (DrawSignature), the copyright line; the party
 * walks up to the dragon (AnimateParty), the dragon breathes fire with a roar of speaker noise
 * and the party is gone (DrawDragonFire, DrawDragonAlone). A key press cuts each step short. Last
 * it chain-loads BOOTUP.BIN over itself at 0100 with an "int 21h" planted at PSP:00FE
 * (docs/HANDOFF.md). The picture pieces are given as scan lines of the 320 x 200 screen; RowTbl
 * holds the screen offset of each line.
 *
 * The screen segment (VideoSeg, ES) is CgaMem. The PSP is Psp[] (u3.h): the FCB at 5Ch (PspFcb),
 * its fields FcbCurBlock (68h), FcbRecSize (6Ah), FcbFileSize (6Ch), FcbCurRec (7Ch), the int 20h
 * at 0000 (PspInt20) and the spot at 00FEh (ChainInt21) where the chain load plants "int 21h".
 * ULTIMA's Location is a 16-byte object here (UDATA); the game's byte is its first.
 */
#include "../u3.h"
#include "../lib/lib.h"
#include "ultima_data.h"
#include "intro.h"

/* ---- data: generated by tools/cdata.py sync (types: c/ultima/types.txt), do not edit between the markers ---- */

/* asm: AnimStepTbl @5FE7 */
u8 AnimStepTbl[] = {
	0x01, 0xFF, 0x01
};

/* asm: AnimEndPicTbl @5FEA */
u8 AnimEndPicTbl[] = {
	0x04, 0xFF, 0x04
};

/* asm: AnimEndXTbl @5FED */
u8 AnimEndXTbl[] = {
	0x34, 0x2B, 0x31
};

/* asm: AnimStartPicTbl @5FF0 */
u8 AnimStartPicTbl[] = {
	0x00, 0x03, 0x00
};

/* ---- end of generated data ---- */

/* ---- the machine, beyond u3.h (BIOS video, the DOS clock, the low memory); not defined ------- */
extern u8 LowMem[0x500];            /* segment 0000: the interrupt vectors, 0040:0010 is LowMem[0x410] */
extern u16 CodeSeg;                 /* CS: the segment of this program, for the vectors */
u8 BiosVideoMode(void);             /* int 10h AH=0Fh: AL = the current video mode (AX goes to CX) */
u16 BiosEquipment(void);            /* int 11h: the equipment list in AX */
void BiosSetMode(u8 al);            /* int 10h AH=0: set the video mode */
void BiosSetColor(u8 bh, u8 bl);    /* int 10h AH=0Bh: BH = 0 background colour BL, BH = 1 palette BL */
void BiosTeletype(u8 al, u8 bl);    /* int 10h AH=0Eh: print AL in colour BL */
void DosBreakCheck(u8 dl);          /* int 21h AH=33h AL=1: set Ctrl-Break checking to DL */
u16 DosGetTime(u16 *cx);            /* int 21h AH=2Ch: returns DX = second:hundredths, *cx = hour:minute */
u16 DosGetDate(u16 *cx);            /* int 21h AH=2Ah: returns DX = month:day, *cx = year */
void DosTerminate(void);            /* the int 20h at PSP:0000 (PspInt20) */

#define OFFSET(f) ((u16)(uintptr_t)(f))     /* `offset BreakHandler`: a routine's address in its segment */

/* ---- helpers that are not routines of the game: words in memory ------------------------------ */
static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }
static void Wr(u8 *p, u16 w) { p[0] = w & 0xFF; p[1] = w >> 8; }

/* asm: CritErrRetry @5CDD returns: BreakHandler -- falls through to BreakHandler's iret */
u8 CritErrRetry(void)
{
    return 1;                                   /* AL = 1: retry the operation */
}

/* asm: BreakHandler @5CDF */
void BreakHandler(void)
{
    /* iret: do nothing */
}

/* asm: StartUp @5CE0 ignore: StackArea PspInt20 ChainInt21 VideoSeg -- the stack, the int 20h and the planted int 21h at PSP:0000 / 00FEh (Psp[], DosTerminate), CgaMem */
void StartUp(void)
{
    /* cld; lea sp, StackArea; add sp, 100h: the stack is the top of the library's StackArea. */
    Wr(&LowMem[0x8C], OFFSET(BreakHandler));    /* vector 23h (0000:008C): Ctrl-Break */
    Wr(&LowMem[0x8E], CodeSeg);
    Wr(&LowMem[0x90], OFFSET(CritErrRetry));    /* vector 24h (0000:0090): critical error */
    Wr(&LowMem[0x92], CodeSeg);
    DosBreakCheck(0);                           /* DOS 33h AL=1 DL=0: Ctrl-Break checking off */
    SetGraphicsMode();
    /* the library's Location (location) = 1: KeyReady does not animate tiles */
    Location[0] = 1;
    /* Seed the 16 bytes of RandState from the clock and the date, twice over. */
    u16 cx, dx;
    dx = DosGetTime(&cx);                       /* CH:CL hour:minute, DH:DL second:hundredths */
    Wr(RandSecHund2, dx);
    Wr(RandSecHund, dx);
    Wr(RandHourMin2, cx);
    Wr(RandHourMin, cx);
    dx = DosGetDate(&cx);                       /* CX year, DH:DL month:day */
    Wr(RandMonthDay2, dx);
    Wr(RandMonthDay, dx);
    Wr(RandYear2, cx);
    Wr(RandState, cx);
    LoadFile(PictureBuf, 0x4000, FileBlankIbm); /* LoadFile saves all: BX = PictureBuf, CX = 4000h still */
    for (u16 i = 0; i < 0x4000 / 2; i++)        /* shr cx, 1 / rep movsw: BLANK.IBM straight to the screen */
        Wr(&CgaMem[i * 2], Rd(&PictureBuf[i * 2]));
    /* RowTbl: 100 pairs of words, 0000 2000 0050 2050 ...: the CGA offset of scan lines 0-199. */
    {
        u16 ax = 0;
        u16 *di = RowTbl;
        for (u16 cx2 = 0x64; cx2 != 0; cx2--) {
            *di++ = ax;
            ax += 0x2000;                       /* odd line: the second bank */
            *di++ = ax;
            ax += 0xE050;                       /* back to the first bank, next line (-2000h + 50h) */
        }
    }
    LoadFile(PictureBuf, 0x4000, FileExodIbm);
    LoadFile(NamePoints, 0x215, FileNameDat);
    DiskCheckResult = DiskCheckStub();          /* the copy protection's stub: AL = 0 here */
    LoadFile(AnimFrames, 0x1700, FileAnimateDat);
    DissolveExodus();
    Delay(2);
    DissolveUltima();
    Delay(5);
    DrawBy();
    Delay(3);
    DrawSignature(0x9FF);                       /* delay between two points of the signature */
    Delay(2);
    DrawCopyright();
    Delay(6);
    /* The copy protection: hang here for ever if the disk check said 0FFh (it never does: the
     * stub returns 0). */
    while (DiskCheckResult == 0xFF) {}          /* StartUp_WaitDisk */
    AnimateParty();
    Delay(4);
    DrawDragonFire();
    if (!KeyReady()) {                          /* jne StartUp_FireOut: a key waits, no roar */
        /* The roar of the fire: 400h toggles of the speaker bit at random intervals
         * (speed-dependent). */
        u8 ah = InPort(0x61);                   /* port 61h: speaker control */
        u8 al = ah & 0xFC;                      /* bits 0-1 off: timer gate and speaker data */
        for (u16 n = 0x400; n != 0; n--) {      /* StartUp_Roar (loop) */
            u8 dl = Random(0xFF);               /* DL = random below 0FFh */
            do { dl--; } while (dl != 0);       /* StartUp_RoarDelay */
            OutPort(0x61, al);
            al ^= 2;                            /* flip the speaker cone */
        }
        OutPort(0x61, ah);                      /* restore port 61h */
    }
    DrawDragonAlone();                          /* StartUp_FireOut */
    Delay(5);
    while (KeyReady())                          /* StartUp_FlushKeys */
        ReadKey();
    /* The chain load (docs/HANDOFF.md): open BOOTUP.BIN with the PSP's FCB, make the record size
     * the file size, plant "int 21h" (CD 21) at PSP:00FE and jump there with AH = 14h (sequential
     * read): DOS reads the whole file to the DTA at 0100, over this program, and returns to 0100,
     * BOOTUP's first instruction. The stack is put below 00FE, out of the way of the load. */
    u8 *fcb = PspFcb;
    DosSetDta(Psp + 0x100);                     /* DOS 1Ah: DTA = 0100, the start of this program */
    DosParseName(FileBootupBin, fcb);           /* DOS 29h (AL = 0): parse the name into the FCB at PSP:005C */
    if (DosOpenFcb(fcb) != 0) {                 /* DOS 0Fh: open the FCB; not found: quit to DOS */
        DosTerminate();                         /* StartUp_Exit: jmp near ptr PspInt20 (the int 20h at PSP:0000) */
        return;
    }
    Wr(FcbRecSize, Rd(FcbFileSize));            /* the file size as the record size */
    Wr(&Psp[0xFE], 0x21CD);                        /* CD 21 = int 21h, planted at PSP:00FE */
    Wr(FcbCurBlock, 0);
    *FcbCurRec = 0;
    /* lea sp, ChainInt21 / jmp near ptr ChainInt21 (the int 21h just planted): AH = 14h (sequential read) is done by the
     * planted int 21h (DX still the FCB); DOS loads BOOTUP.BIN at 0100 and returns to 0100: the
     * C unwinds here, ULTIMA's code is gone. */
    DosReadFcb(fcb);
}

/* asm: Delay @5E5A */
void Delay(u16 ax)
{
    if (KeyReady()) return;                     /* jne Delay_Done: a key waits, no delay at all */
    u16 cx = 0;
    do {
        do { cx--; } while (cx != 0);           /* Delay_Loop: `loop`, 65536 turns from CX = 0 */
        ax--;
    } while (ax != 0);                          /* AX = 0 at the start would run 65536 times */
}

/* asm: DrawSignature @5E68 ignore: VideoSeg -- CgaMem stands for the screen segment */
void DrawSignature(u16 si)
{
    const u8 *bx = NamePoints;
    if (KeyReady()) return;
    for (;;) {
        u8 cl = *bx;                            /* x */
        if (cl == 0) break;                     /* x = 0: the end */
        bx++;
        u8 ch = 0xC0 - *bx;                     /* row = 192 - y */
        bx++;
        PlotPixel(cl, ch);
        cl++;
        PlotPixel(cl, ch);
        u16 cx = si;
        do { cx--; } while (cx != 0);           /* DrawSignature_Wait: SI turns (0 = 65536) */
        if (KeyReady()) break;                  /* je DrawSignature_Loop while no key */
    }
}

/* asm: DissolveExodus @5E96 */
void DissolveExodus(void)
{
    u8 al = 0;
    do {
        if (KeyReady()) break;                  /* jne DissolveExodus_Full */
        /* AH = FFh (dissolve), CX = 7: from byte 7 of the line (pixel 28), BL = 8: picture line 8,
         * BH = 8: screen line 8, DL = 4Dh: 77 lines, DH = 21h: 33 words (264 pixels) wide */
        CopyPicture(8, 8, 0x4D, 0x21, 7, 0xFF, al);
        al += 4;
    } while (al != 0);                          /* 64 passes: AL = 0, 4, ... 0FCh */
    CopyPicture(8, 8, 0x4D, 0x21, 7, 0, al);    /* DissolveExodus_Full: the plain copy */
}

/* asm: DrawDragonFire @5EC2 */
void DrawDragonFire(void)
{
    if (KeyReady()) return;
    CopyPicture(0xA8, 0xA8, 0x10, 0x0B, 0x1D, 0, 0xFF);     /* AL: whatever KeyReady left (unused with AH = 0) */
}

/* asm: DrawDragonAlone @5ED8 */
void DrawDragonAlone(void)
{
    if (KeyReady()) return;
    CopyPicture(0x98, 0xA8, 0x10, 0x0C, 0x1D, 0, 0xFF);     /* from picture line 152 to screen line 168 */
}

/* asm: DissolveUltima @5EEE */
void DissolveUltima(void)
{
    u8 al = 0;
    do {
        if (KeyReady()) break;                  /* jne DissolveUltima_Full */
        CopyPicture(0x55, 0x55, 0x2B, 0x21, 7, 0xFF, al);
        al += 4;
    } while (al != 0);
    CopyPicture(0x55, 0x55, 0x2B, 0x21, 7, 0, al);          /* DissolveUltima_Full */
}

/* asm: DrawBy @5F1A */
void DrawBy(void)
{
    if (KeyReady()) return;
    CopyPicture(0x84, 0x84, 9, 4, 0x11, 0, 0xFF);
}

/* asm: DrawCopyright @5F30 */
void DrawCopyright(void)
{
    CopyPicture(0x92, 0x92, 5, 0x20, 5, 0, 0xFF);           /* always, even with a key waiting */
}

/* asm: PlotPixel @5F41 ignore: VideoSeg -- CgaMem stands for the screen segment (ES) */
void PlotPixel(u8 cl, u8 ch)
{
    cl += 0x14;                                 /* x + 20 */
    u8 al = cl >> 2;                            /* AL = byte of the line (4 pixels a byte) */
    u8 ah = 0xC0;                               /* both bits of the leftmost pixel, shifted to the pixel */
    ah >>= (cl & 3) * 2;
    u16 bx = RowTbl[ch];                        /* bl = ch, bh = 0 */
    bx += al;                                   /* add bl, al / adc bh, 0 */
    CgaMem[bx] |= ah;
}

/* asm: CopyPicture @5F6C ignore: VideoSeg -- CgaMem stands for the screen segment (ES) */
void CopyPicture(u8 bl, u8 bh, u8 dl, u8 dh, u16 cx, u8 ah, u8 al)
{
    /* [bp+0Eh] = cx: first byte of each line; [bp+2] = bl, bh: picture line, screen line;
     * [bp] = al AND 0F8h: threshold, [bp+1] = ah: dissolve flag. */
    u8 threshold = al & 0xF8;
    u8 pic = bl, scr = bh;                      /* [bp+2] */
    for (;;) {                                  /* CopyPicture_Line */
        const u8 *si = PictureBuf + RowTbl[pic] + cx;
        u8 *di = CgaMem + RowTbl[scr] + cx;
        for (u16 n = dh; n != 0; n--) {         /* CopyPicture_Word: CL = DH words (CH = 0) */
            u16 w;
            if (ah != 0) {                      /* dissolve */
                u16 r = Rd(DissolveRand);       /* next pseudo-random byte: AL' = AL + 1Dh + AH' = AL + 1Dh */
                u8 rl = r & 0xFF, rh = r >> 8;
                rl += 0x1D;
                u8 t = rl;                      /* mov bl, al */
                rl += rh;
                rh = t;
                Wr(DissolveRand, rl | (rh << 8));
                if (rl > threshold) {           /* cmp al, [bp] / jbe: not yet: black */
                    w = 0;
                    si += 2;
                    Wr(di, w);                  /* CopyPicture_Store */
                    di += 2;
                    continue;
                }
                /* CopyPicture_Click: a click of the speaker (timer gate off) */
                u8 p = InPort(0x61);
                p ^= 2;                         /* flip the speaker bit */
                p &= 0xFE;
                OutPort(0x61, p);
            }
            w = Rd(si);                         /* CopyPicture_Copy: lodsw */
            si += 2;
            Wr(di, w);                          /* CopyPicture_Store: stosw */
            di += 2;
        }
        pic++;                                  /* add word ptr [bp+2], 101h: next picture line and screen line */
        scr++;
        dl--;
        if (dl == 0) break;                     /* (DL = 0 at the start would be 256 lines) */
    }
}

/* The three phases of AnimateParty, indexed 2, 1, 0 (in that order): the party walks right
 * (pictures 0-3 at each x 42 to 49), back left (pictures 3-0, x 49 to 43), then right
 * again up to the dragon (x 43 to 52). The four tables are generated above. */

/* asm: AnimateParty @5FF3 */
void AnimateParty(void)
{
    i16 si = 2;
    u8 bl = 0x2A;                               /* x = 42 (pixel 104); BH stays 0 */
    for (;;) {
        u8 al;
        if (KeyReady()) return;                 /* AnimateParty_Step */
        al = AnimStartPicTbl[si];
        do {
            DrawAnimFrame(al, bl);              /* AnimateParty_Frame (AH = 0 since the start) */
            for (u16 cx = 0x9000; cx != 0; cx--) {}     /* AnimateParty_Wait */
            al += AnimStepTbl[si];
        } while (al != AnimEndPicTbl[si]);
        bl += AnimStepTbl[si];
        if (bl != AnimEndXTbl[si]) continue;    /* jne AnimateParty_Step */
        si--;
        if (si < 0) return;                     /* jns AnimateParty_Step */
    }
}

/* asm: DrawAnimFrame @6024 ignore: VideoSeg -- CgaMem stands for the screen segment (ES) */
void DrawAnimFrame(u8 al, u16 bx)
{
    bx <<= 1;
    bx += 0x14;                                 /* BX = pixel column */
    u16 di = (u16)(al * 0x5C0);                 /* mul cx, CX = 5C0h: 1472 bytes a picture (4 shifts); AH = 0 */
    u16 dx = bx & 3;
    u16 ax = (u16)(0x170 * dx);                 /* 368 bytes a shift (16 x 23) */
    ax += di;
    bx >>= 2;
    dx = bx;                                    /* DX = the byte of the line */
    const u8 *si = AnimFrames + ax;
    bx = 0x150;                                 /* RowTbl entry of line 168 (RowTbl[84], 2 bytes each) */
    for (u16 rows = 0x10; rows != 0; rows--) {  /* 16 rows */
        u16 line = RowTbl[bx / 2];
        bx += 2;
        u8 *p = CgaMem + line + dx;
        p[-1] = 0;                              /* a cleared byte on each side wipes the previous position */
        for (int i = 0; i < 0x17; i++)          /* rep movsb: 23 bytes */
            p[i] = *si++;
        p[0x17] = 0;
    }
}

/* asm: SetGraphicsMode @607E ignore: VideoSeg -- CgaMem stands for the screen segment (ES) */
void SetGraphicsMode(void)
{
    u8 mode = BiosVideoMode();                  /* BIOS 10h/0Fh: current video mode in AL (AX in CX) */
    if (mode == 7) {                            /* monochrome text? */
        u16 cx = BiosEquipment();               /* BIOS equipment list in AX */
        /* write and read back three patterns at B800:0000 */
        u16 saved = Rd(&CgaMem[0]);
        Wr(&CgaMem[0], 0x5555);
        if (Rd(&CgaMem[0]) != 0x5555) goto fail;
        Wr(&CgaMem[0], 0xAAAA);
        if (Rd(&CgaMem[0]) != 0xAAAA) goto fail;
        Wr(&CgaMem[0], 0xD221);
        if (Rd(&CgaMem[0]) != 0xD221) goto fail;
        Wr(&CgaMem[0], saved);
        u16 ax = Rd(&LowMem[0x410]);            /* 0040:0010, the BIOS equipment word */
        if (ax != cx) goto fail;                /* (leaves ES on the stack: it hangs anyway) */
        ax &= 0xFFEF;                           /* initial video mode bits 5-4: 11 (mono) -> 10 (80 x 25 colour) */
        Wr(&LowMem[0x410], ax);
    }
    BiosSetMode(4);                             /* SetGraphicsMode_Set: mode 4, 320 x 200 x 4 colours */
    BiosSetColor(0, 0);                         /* BIOS 10h/0Bh BH=0: background colour 0, black */
    BiosSetColor(1, 1);                         /* BIOS 10h/0Bh BH=1: palette 1 */
    CursorRow = 0;
    CursorCol = 0;
    return;
fail:                                           /* SetGraphicsMode_Fail */
    for (const u8 *si = MsgNoGraphics; *si != 0; si++)      /* SetGraphicsMode_Print */
        BiosTeletype(*si, 7);                   /* BIOS 10h/0Eh: teletype output, BL = 7 */
    for (;;) {}                                 /* SetGraphicsMode_Hang: jmp to itself */
}

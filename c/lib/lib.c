/* asm: ParseNumber @488E */
u16 ParseNumber(const u8 *si, u16 cx, u16 *bxp)
{
    u16 dx = 0xFFFE;                            /* DX = -2: no number */
    u16 bx = 0;
    u8 al;
    while (cx != 0) {                           /* skip spaces */
        if (*si != 0x20) goto first;
        si++;
        cx--;
    }
    return dx;
first:
    al = *si;                                   /* the first character must be a hex digit */
    if (al < 0x30) return dx;
    if (al > 0x39) {
        if (al < 0x41) return dx;
        if (al > 0x46) {
            if (al < 0x61) return dx;
            if (al > 0x66) return dx;
        }
    }
    bx = 0;                                     /* BX = hex/BCD value */
    dx = 0;                                     /* DX = decimal value */
    for (;;) {
        if (cx == 0) break;
        cx--;
        al = *si++;
        if (al < 0x30) break;
        if (al > 0x39) {
            if (al < 0x41) break;
            if (al > 0x46) {
                al -= 0x20;                     /* a-f to A-F */
                if (al < 0x41) break;
                if (al > 0x46) break;
            }
        }
        bx <<= 4;
        al -= 0x30;                             /* AL = digit value */
        if (al > 9) al -= 7;
        bx |= al;                               /* or bl, al */
        if (dx == 0xFFFF) continue;             /* a hex digit came: only BX goes on */
        if (al > 9) { dx = 0xFFFF; continue; }  /* DX = -1: not decimal */
        dx = dx * 10 + al;
    }
    *bxp = bx;                                  /* BX is only set when a digit was found */
    return dx;
}

/* asm: AskChoice @4918 ignore: CursorCol -- GetCursor/SetCursor stand for the word access */
u8 AskChoice(u16 cx, const u8 *di, const u8 *const *si)
{
    const u8 *const *bx = si;                   /* BX = the string table */
    u16 dx = GetCursor();                       /* DX = where the answer is printed */
    if (cx == 0) return 0;                      /* jcxz: AL is left as the caller had it (no value here) */
    for (;;) {
        u16 ax = ReadKey();
        u8 al = ax & 0xFF;
        int entry = -1;
        if (al != 0) {                          /* no character: beep */
            if (al >= 0x61 && al <= 0x7A) al -= 0x20;      /* lower case to upper */
            for (u16 k = 0; k < cx; k++)        /* repne scasb over the CX letters at DI */
                if (di[k] == al) { entry = k; break; }
        }
        if (entry < 0) { Sound(0xFE); continue; }
        u16 len = PrintStrLen(bx[entry]);       /* print it, CX = its length */
        for (;;) {                              /* AskChoice_Confirm */
            u16 k = ReadKey();
            if (k == 0x1C0D) return al;         /* Enter: done, AL = the letter */
            if (k == 0x4B00 || k == 0x0E08) {   /* cursor left / Backspace: undo */
                SetCursor(dx);                  /* back to the start, */
                for (u16 n = len; n != 0; n--)  /* blank what was printed */
                    PutChar(0x20);
                SetCursor(dx);
                break;                          /* and ask again */
            }
            Sound(0xFE);
        }
    }
}

/* asm: ReadNumber @498F ignore: CursorCol -- GetCursor/SetCursor stand for the word access */
u16 ReadNumber(void)
{
    u8 buf[2];                                  /* a 2-byte buffer on the stack (ES = SS) */
    u16 dx = GetCursor();                       /* DX = where the number goes */
    for (;;) {
        dx = SwapCursor(dx);
        PutChar(0x20);                          /* blank 2 columns */
        PutChar(0x20);
        SetCursor(dx);
        u16 bx = ReadLine(buf, 2);              /* BX = characters typed */
        u16 ax = dx;                            /* AX = the cursor position */
        dx = ParseNumber(buf, bx, &bx);
        if (dx == 0xFFFE) {                     /* no digit: beep and again */
            SetCursor(ax);
            dx = ax;
            Sound(0xFE);
            continue;
        }
        return (u16)(((dx & 0xFF) << 8) | (bx & 0xFF));   /* AL = BCD value, AH = decimal value */
    }
}


/* asm: SaveFile @49E0 */
void SaveFile(u8 *bx, u16 cx, const u8 *dx)
{
    u8 *fcb = &Psp[0x5C];                       /* DI = the FCB at PSP:5Ch */
    DosSetDta(bx);                              /* DOS: set the DTA to BX */
    DosParseName(dx, fcb);                      /* DOS: parse the name (AL = 0) into it */
    OpenFile(fcb);                              /* the file must exist */
    Wr(&Psp[0x68], 0);                          /* FCB current block = 0 */
    Psp[0x7C] = 0;                              /* FCB current record = 0 */
    Wr(&Psp[0x6A], cx);                         /* FCB record size = CX */
    if (DosWriteFcb(fcb) == 0) {                /* DOS: sequential write */
        DosCloseFcb(fcb);
        return;
    }
    PrintAt(0x1800, MsgUnableWrite);            /* row 18h, column 0 */
    PrintStr(MsgBlankLine);                     /* meant: the name; but OpenFile set SI = MsgBlankLine */
    Hang();                                     /* SaveFile_Hang: jmp SaveFile_Hang */
}

/* asm: LoadFile @4A30 */
void LoadFile(u8 *bx, u16 cx, const u8 *dx)
{
    u8 *fcb = &Psp[0x5C];                       /* DI = the FCB at PSP:5Ch */
    DosSetDta(bx);                              /* DOS: set the DTA to BX */
    DosParseName(dx, fcb);                      /* DOS: parse the name (AL = 0) into it */
    OpenFile(fcb);
    if (Rd(&Psp[0x6C]) == 0) {                  /* FCB file size, low word */
        PrintAt(0x1800, MsgUnableRead);         /* row 18h, column 0 */
        PrintStr(MsgBlankLine);                 /* meant: the name; but OpenFile set SI = MsgBlankLine */
        Hang();                                 /* LoadFile_Hang */
        return;
    }
    Wr(&Psp[0x68], 0);                          /* FCB current block = 0 */
    Psp[0x7C] = 0;                              /* FCB current record = 0 */
    Wr(&Psp[0x6A], cx);                         /* FCB record size = CX */
    DosReadFcb(fcb);                            /* DOS: sequential read */
    DosCloseFcb(fcb);
}

/* asm: OpenFile @4A83 ignore: CursorCol -- GetCursor/SetCursor stand for the word access */
void OpenFile(u8 *di)
{
    u16 saved = GetCursor();                    /* save the cursor */
    for (;;) {
        if (DosOpenFcb(di) != 0xFF) break;      /* 0FFh: not found */
        SetCursor(0x1800);                      /* row 18h, column 0 */
        PrintStr(MsgWrongDiskette);
        Sound(0xFE);                            /* error beep */
        while (!KeyReady()) {}                  /* wait for a key */
        ReadKey();                              /* and drop it */
    }
    PrintAt(0x1800, MsgBlankLine);              /* blank the message line (SI = MsgBlankLine stays) */
    SetCursor(saved);
}

/* asm: PrintAt @4ABE */
void PrintAt(u16 dx, const u8 *si)
{
    SwapCursor(dx);
    PrintStr(si);                               /* the cursor stays after the text (DX is popped) */
}

/* asm: SignStep @4AC7 */
i8 SignStep(u8 *al)
{
    u8 a = *al;
    if (Location == 0) a <<= 2;                 /* Sosaria: the map wraps at 64, so AL counts as 6-bit signed */
    i8 ah = ((i8)a < 0) ? -1 : 0;               /* cbw */
    if ((i8)a > 0) ah = 1;                      /* positive: AH = +1 (zero and negative keep AH) */
    if (Location == 0) a >>= 2;                 /* AL back, top two bits cleared */
    *al = a;
    return ah;
}


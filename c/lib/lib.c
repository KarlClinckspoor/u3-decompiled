/* asm: Sound @4B99 */
void Sound(u8 al)
{
    if (SoundOn == 0) return;
    if (al < 0xF4) return;                      /* below 0F4h: nothing */
    unsigned di = (u8)(~al << 1);               /* DI = (0FFh - AL) * 2 */
    ((void (*)(void))SoundTbl[di / 2])();       /* call word ptr SoundTbl[di]; BX, DX as the caller left them */
}

/* Port 61h's speaker bit: every sound routine reads it, clears the timer gate and speaker data,
 * toggles bit 1 in timed loops and writes the old value back. The delays are `dec`/`loop`
 * counts (CPU speed dependent, no timer). */

/* asm: SndBuzz @4BB9 */
void SndBuzz(void)
{
    u8 saved = InPort(0x61);                    /* port 61h: the speaker control */
    u8 al = saved & 0xFC;                       /* timer 2 gate and speaker data off */
    for (u16 cx = 0x10; cx != 0; cx--) {
        OutPort(0x61, al);
        al ^= 2;                                /* toggle the speaker */
        for (u16 di = 1; di != 0; di--)
            for (u16 bx = 0x3E8; bx != 0; bx--) {}      /* delay (CPU speed) */
    }
    OutPort(0x61, saved);
}

/* asm: SndBeep @4BDB */
void SndBeep(void)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    for (u16 cx = 0x30; cx != 0; cx--) {
        OutPort(0x61, al);
        al ^= 2;
        for (u16 di = 1; di != 0; di--)
            for (u16 bx = 0x163; bx != 0; bx--) {}
    }
    OutPort(0x61, saved);
}

/* asm: SndWarble @4BFD */
void SndWarble(u8 bl, u8 bh)                    /* BL, BH are the caller's (SndWarbleE0: 0E0h, 4) */
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    u8 ch = bl;                                 /* CH = high time */
    u8 cl = 1;                                  /* CL = low time */
    do {
        for (u8 dl = bh; dl != 0; dl--) {
            for (u8 dh = ch; --dh != 0;) {}     /* `dec dh / jne`: a count of 0 runs 256 times */
            OutPort(0x61, al);
            al ^= 2;
            for (u8 dh = cl; --dh != 0;) {}
            OutPort(0x61, al);
            al ^= 2;
        }
        ch--;
        cl++;
    } while (cl != 0x1B);                       /* then the same back */
    do {
        for (u8 dl = bh; dl != 0; dl--) {
            for (u8 dh = ch; --dh != 0;) {}
            OutPort(0x61, al);
            al ^= 2;
            for (u8 dh = cl; --dh != 0;) {}
            OutPort(0x61, al);
            al ^= 2;
        }
        cl--;
        ch++;
    } while (cl != 0);
    OutPort(0x61, saved);
}

/* asm: SndNoise @4C56 */
void SndNoise(u8 bl)                            /* BL: the caller's (?) */
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    for (u8 bh = 0x80; bh != 0; bh--) {
        u8 dl = Random(0x0F);                   /* DL = 0-14 */
        dl = (u8)(dl + bl);                     /* adc dl, bl: plus the carry flag Random's `ret` leaves (popf: the caller's) */
        do {
            for (u16 cx = 3; cx != 0; cx--) {}
        } while (--dl != 0);
        OutPort(0x61, al);
        al ^= 2;
    }
    OutPort(0x61, saved);
}

/* asm: SndFall @4C7F */
void SndFall(void)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    for (u8 bl = 0xFB; bl != 0; bl--) {         /* half-wave length 256 - BL */
        OutPort(0x61, al);
        al ^= 2;
        for (u8 bh = bl; ++bh != 0;) {}
    }
    OutPort(0x61, saved);
}

/* asm: SndRise @4C9A */
void SndRise(void)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    for (u8 bh = 0xA0; bh != 0; bh--) {         /* half-wave length BH, 160 down to 1 */
        for (u16 cx = bh; --cx != 0;) {}        /* CH = 0, CL = BH */
        OutPort(0x61, al);
        al ^= 2;
    }
    OutPort(0x61, saved);
}

/* asm: SndWarbleE0 @4CB8 */
void SndWarbleE0(void)
{
    SndWarble(0xE0, 4);
}

/* asm: SndNoiseRise @4CC2 */
void SndNoiseRise(void)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    u8 bl = 0xE0;
    u8 bh = 0x40;
    do {
        u8 dl = Random(0xFF);
        dl |= bl;                               /* the floor drops from 0E0h to 40h */
        while (--dl != 0) {}
        OutPort(0x61, al);
        al ^= 2;
        bl--;
    } while (bl != bh);
    OutPort(0x61, saved);
}

/* asm: SndHit @4CE8 */
void SndHit(void)
{
    NoiseBurst(0xFF, 0);                        /* BL = 0FFh half-waves, BH = 0 */
}

/* asm: SndTick @4CF2 */
void SndTick(void)
{
    NoiseBurst(8, 0);
}

/* asm: NoiseBurst @4CFC */
void NoiseBurst(u8 bl, u8 bh)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    do {
        u8 dl = Random(0xFF) | bh;              /* Random(0-254) OR BH long */
        while (--dl != 0) {}
        OutPort(0x61, al);
        al ^= 2;
    } while (--bl != 0);
    OutPort(0x61, saved);
}

/* asm: SndTrill @4D1E */
void SndTrill(u8 dl)                            /* DL: the caller's, 8-38 notes */
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    u8 cl = (u8)((dl & 0x0F) * 2 + 8);
    do {
        u8 len = Random(0xFF);                  /* DL = the note's length */
        for (u8 ch = 0x28; ch != 0; ch--) {     /* 40 half-waves a note */
            for (u8 dh = len; --dh != 0;) {}
            OutPort(0x61, al);
            al ^= 2;
        }
    } while (--cl != 0);
    OutPort(0x61, saved);
}

/* asm: SndSlowFall @4D4E */
void SndSlowFall(void)
{
    u8 saved = InPort(0x61);
    u8 al = saved & 0xFC;
    u8 bl = 0x40;                               /* half-wave length 40h .. 0BFh */
    do {
        for (u8 bh = 0x1E; bh != 0; bh--) {     /* 30 half-waves each */
            for (u8 cl = bl; --cl != 0;) {}
            OutPort(0x61, al);
            al ^= 2;
        }
        bl++;
    } while (bl < 0xC0);
    OutPort(0x61, saved);
}

/* ---- helpers that are not routines of the game: words in memory, a CGA word ------------------ */

static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }
static void Wr(u8 *p, u16 w) { p[0] = w & 0xFF; p[1] = w >> 8; }
static u16 Xchg(u8 *p, u16 w) { u16 old = Rd(p); Wr(p, w); return old; }     /* xchg word ptr [p], reg */
static void Poke(u16 off, u16 w) { Wr(&CgaMem[off], w); }                  /* mov es:[off], ax */


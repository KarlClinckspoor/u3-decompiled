/* asm: PrintStrLen @43EB */
u16 PrintStrLen(const u8 *si)
{
    u16 cx = 0;
    for (;;) {
        u8 al = *si++;                          /* lodsb */
        if (al == 0) break;                     /* NUL ends */
        cx++;
        PutChar(al);
    }
    return cx;
}


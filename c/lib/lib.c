/* asm: ScrollTile @463A */
void ScrollTile(u8 *dx, u16 bx)
{
    u8 *t = dx + bx;                            /* BX = the tile */
    u16 ax = Rd(t + 0x3C);                      /* AX:DX = line 15 (the last odd line) */
    u16 d = Rd(t + 0x3E);
    for (int cx = 8; cx != 0; cx--) {
        ax = Xchg(t, ax);                       /* even line 2i gets the line above (odd 2i-1) */
        ax = Xchg(t + 0x20, ax);                /* odd line 2i+1 gets even line 2i */
        d = Xchg(t + 2, d);
        d = Xchg(t + 0x22, d);
        t += 4;
    }
}

/* asm: AnimScroll @4660 */
void AnimScroll(void)
{
    u8 *dx = TileGfx;                           /* the tiles of TileGfx */
    if (--WaterCount == 0) {
        ScrollTile(dx, 0);                      /* tile 0: water */
        WaterCount = 3;
    }
    if (--LavaCount == 0) {
        ScrollTile(dx, 0x840);                  /* tile 33: lava */
        LavaCount = 2;
    }
    if (--FieldCount == 0) {
        ScrollTile(dx, 0x800);                  /* tile 32: force field */
        FieldCount = 3;
    }
    if (--GateCount == 0) {
        ScrollTile(dx, 0x880);                  /* tile 34: moon gate */
        GateCount = 2;
    }
}

/* asm: AnimFlags @46AF */
void AnimFlags(void)
{
    if (--CastleFlagCount == 0) {
        u8 *bx = TileGfx + 0x1C0;               /* tile 7: castle */
        u16 ax = Rd(bx + 0x20);                 /* odd line 0 (pixel line 1) */
        u16 di = Rd(bx + 0x22);
        ax = Xchg(bx + 4, ax);                  /* swapped with even line 1 (pixel line 2) */
        di = Xchg(bx + 6, di);
        Wr(bx + 0x20, ax);
        Wr(bx + 0x22, di);
        CastleFlagCount = 4;
    }
    if (--TowneFlagCount == 0) {
        u8 *bx = TileGfx + 0x180;               /* tile 6: towne */
        u16 ax = Rd(bx + 0x24);                 /* pixel line 3 */
        u16 di = Rd(bx + 0x26);
        ax = Xchg(bx + 8, ax);                  /* swapped with pixel line 4 */
        di = Xchg(bx + 0xA, di);
        Wr(bx + 0x24, ax);
        Wr(bx + 0x26, di);
        TowneFlagCount = 3;
    }
    if (--ShipFlagCount == 0) {
        u8 *bx = TileGfx + 0x2C0;               /* tile 11: frigate */
        u16 ax = Rd(bx + 4);                    /* pixel line 2 */
        u16 di = Rd(bx + 6);
        ax = Xchg(bx + 0x24, ax);               /* swapped with pixel line 3 */
        di = Xchg(bx + 0x26, di);
        Wr(bx + 4, ax);
        Wr(bx + 6, di);
        ShipFlagCount = 2;
    }
}

/* asm: SwapFrames @4727 */
void SwapFrames(void)
{
    if (--FrameCount != 0) return;
    FrameCount = 0x0A;
    u8 *si = AltFrameGfx;
    u8 *di = FigureGfx;
    for (int cx = 0x1E0; cx != 0; cx--) {       /* 960 bytes: tiles 64-78 <-> 16-30 */
        u16 ax = Rd(di);
        ax = Xchg(si, ax);
        si += 2;
        Wr(di, ax);                             /* stosw */
        di += 2;
    }
    di = WhirlpoolGfx;
    for (int cx = 0x20; cx != 0; cx--) {        /* 64 bytes: tile 79 <-> 12 (whirlpool); SI runs on */
        u16 ax = Rd(di);
        ax = Xchg(si, ax);
        si += 2;
        Wr(di, ax);
        di += 2;
    }
}

/* asm: BlinkPlayer @4768 unrolled: ViewTileAt-1 -- the two branches share one call */
void BlinkPlayer(void)
{
    if (Location != 0x80) return;               /* in combat only */
    u8 al = BlinkCount;                         /* count BlinkCount towards 0 */
    i8 ah = -SignStep(&al);                     /* neg ah */
    BlinkCount += ah;
    if (BlinkCount != 0) return;
    u8 *bx;
    if (ah < 0) {                               /* was counting down (test ah, 0FFh / jns not taken) */
        BlinkCount = 0xFD;                      /* hide him for 3 calls */
        ah = CombatUnderTile[CombatPlayer];     /* the tile under him */
    } else {                                    /* was counting up: show him for 10 */
        BlinkCount = 0x0A;
        ah = CombatPartyTile[CombatPlayer];     /* his own tile */
    }
    ViewTileAt(CombatPartyX[CombatPlayer], CombatPartyY[CombatPlayer], &bx);
    *bx = ah;                                   /* into the view buffer */
}

/* asm: Animate @47C7 */
void Animate(void)
{
    if (Location != 0x80 && Location != 4)      /* no wind in combat or in a shrine */
        WindUpdate();
    AnimScroll();
    AnimFlags();
    BlinkPlayer();
    SwapFrames();
    DrawView();
}

/* asm: KeyReady @47EA */
bool KeyReady(void)                             /* true = a key waits (ZF clear) */
{
    bool waiting = BiosKeyWaiting();            /* int 16h AH=1 */
    if (Location != 1)                          /* dungeon (and ULTIMA): no animation */
        Animate();
    return waiting;                             /* the flags of the int, popped after Animate */
}

/* asm: ReadKey @47FD */
u16 ReadKey(void)
{
    if (!KeyReady()) {
        for (;;) {
            DrawChar(0x1E);                     /* the cursor glyph */
            u16 cx = 0x50;                      /* 80 polls */
            bool key;
            do {
                key = KeyReady();
                cx--;
            } while (cx != 0 && !key);          /* loope */
            if (key) break;
            IdleNop();                          /* then the empty hook, and again */
        }
        DrawChar(0x20);                         /* erase the cursor */
    }
    if (Location == 0x80) {                     /* combat: put the active member back */
        u8 *bx = ViewTiles + CombatPlayer;      /* lea bx, ViewTiles[bx]: the combat arrays follow the view */
        u8 ah = bx[0xAC];                       /* CombatPartyTile */
        u8 *cell;
        ViewTileAt(bx[0xA0], bx[0xA4], &cell);  /* CombatPartyX / CombatPartyY */
        *cell = ah;
        DrawView();
        BlinkCount = 2;                         /* and blink again soon */
    }
    return BiosReadKey();                       /* int 16h AH=0 */
}


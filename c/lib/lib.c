/* asm: DrawTileBlock @4528 ignore: ScreenSeg -- CgaMem stands for the screen segment */
void DrawTileBlock(u8 ah, u8 al, const u8 *bx, const u8 *bp, u16 di)
{
    u8 dh = al * 4;                             /* bytes in a row of tiles */
    for (; ah != 0; ah--) {                     /* rows */
        for (u8 dl = al; dl != 0; dl--) {       /* tiles in the row */
            u16 si = (*bx & 0xFF) * 64;         /* `mov si, word ptr [bx]` / `and si, 0FFh`: the tile byte */
            bx++;
            const u8 *g = bp + si;              /* SI = BP + tile * 64 */
            for (int i = 0; i < 8; i++) {       /* 8 even lines of 4 bytes, 80 apart */
                Poke(di, Rd(g)); Poke(di + 2, Rd(g + 2));
                g += 4;
                di += 4 + 0x4C;
            }
            di += 0x1D80;                       /* + 280h = 2000h: the same place in bank 1 */
            for (int i = 0; i < 8; i++) {       /* 8 odd lines */
                Poke(di, Rd(g)); Poke(di + 2, Rd(g + 2));
                g += 4;
                di += 4 + 0x4C;
            }
            di -= 0x227C;                       /* back to bank 0, 4 bytes (16 pixels) right */
        }
        di += 0x280 - dh;                       /* next row: 16 pixel lines down, back to the left */
    }
}

/* asm: ClearScreen @4589 ignore: CursorCol ScreenSeg -- GetCursor/SetCursor, CgaMem */
void ClearScreen(void)
{
    for (u16 i = 0; i < 0xFA0; i++) Poke(i * 2, 0);                /* 8000 bytes of bank 0 */
    for (u16 i = 0; i < 0xFA0; i++) Poke(0x2000 + i * 2, 0);       /* and of bank 1 */
    SetCursor(0);                               /* cursor to column 0, row 0 */
}


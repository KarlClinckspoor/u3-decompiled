/* asm: DrawView @4AEA */
void DrawView(void)
{
    DrawTileBlock(0x0B, 0x0B, ViewTiles, TileGfx, 0x142);      /* 11 rows, 11 columns; row 1 (320) + 2 bytes */
}

/* asm: ViewTileAt @4B05 */
u8 ViewTileAt(u8 bl, u8 bh, u8 **bxp)
{
    bh = (u8)(bh * 11);                         /* BH = BH * 11 (8-bit) */
    bl = (u8)(bl + bh);
    *bxp = ViewTiles + bl;                      /* BX = its address (BH cleared first: BL stays 8-bit) */
    return **bxp;
}

/* asm: WindUpdate @4B2A ignore: CursorCol -- GetCursor/SetCursor stand for the word access */
void WindUpdate(void)
{
    if (--WindCount == 0) {
        WindCount = 0x19;                       /* 25 calls until the next change */
        for (;;) {
            u8 dl = Random(9);                  /* DL = 0-8 */
            if (dl >= 5) {                      /* 0-4: that wind; 5-8: north .. west, but a change */
                dl -= 4;
                if (dl == WindDir) continue;
            }
            WindDir = dl;
            break;
        }
    }
    u16 dx = SwapCursor(0x1706);                /* row 17h, column 6: xchg word ptr CursorCol, dx */
    PrintStr(WindMsgTbl[WindDir]);              /* SI = WindDir as a word, the high byte masked off */
    SetCursor(dx);
}


/* asm: ReadLine @45B3 */
u16 ReadLine(u8 *di, u16 cx)
{
    u16 bx = cx;                                /* BX = room at the start */
    for (;;) {
        u16 ax = ReadKey();
        u8 al = ax & 0xFF;
        if (ax == 0x0E08 || ax == 0x0E7F || ax == 0x4B00) {        /* Backspace, Ctrl-Backspace, cursor left */
            if (bx == cx) { Sound(0xFE); continue; }               /* nothing to delete: beep */
            PutChar(8);
            cx++;
            di--;
            *di = 0x20;                         /* blank it in the buffer too */
            continue;
        }
        if (ax == 0x1C0D)                       /* Enter */
            return bx - cx;                     /* BX = characters typed */
        if (al < 0x20 || al >= 0x80 || cx == 0) {   /* control, not ASCII, or buffer full (jcxz) */
            Sound(0xFE);                        /* error beep */
            continue;
        }
        *di++ = al;                             /* stosb: no NUL is stored */
        PutChar(al);
        cx--;
    }
}

/* asm: Random @4601 */
u8 Random(u8 dh)
{
    /* std: backwards from the low end. Bytes 14 down to 0 each get the next byte (+1) and the carry
     * added: RandState is one 128-bit number, byte 0 the most significant. */
    unsigned carry = 0;
    for (int i = 14; i >= 0; i--) {
        unsigned sum = RandState[i] + RandState[i + 1] + carry;
        RandState[i] = sum & 0xFF;
        carry = sum >> 8;
    }
    /* then the whole number is incremented: `loope` carries while a byte wrapped to 0 */
    for (int i = 15; i >= 0; i--) {
        RandState[i]++;
        if (RandState[i] != 0) break;
    }
    u8 dl = RandState[0];                       /* byte 0, reduced by repeated subtraction of DH */
    while (dl >= dh)                            /* DH = 0 would loop for ever */
        dl -= dh;
    return dl;
}


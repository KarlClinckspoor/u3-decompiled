/* asm: CheckAlive @1D95 */
u8 CheckAlive(const u8 *bx)
{
    /* AL = 0 when the record at BX is Good or Poisoned, else 0FFh (dead, ashes or empty). */
    if (bx[0x11] == 0x47) return 0;             /* status 'G' */
    if (bx[0x11] == 0x50) return 0;             /* status 'P' */
    return 0xFF;
}

/* asm: AnyAlive @1DA8 */
u8 AnyAlive(void)
{
    /* AH = 0FFh when one of the four party records (PartyChars, all four whatever the party size)
     * is Good or Poisoned, else 0. */
    const u8 *bx = PartyChars;
    for (u16 cx = 4; cx != 0; cx--) {           /* AnyAlive_Loop */
        if (CheckAlive(bx) == 0) return 0xFF;
        bx += 0x40;
    }
    return 0;
}

/* asm: AskScenarioDisk @1DC6 */
void AskScenarioDisk(void)
{
    /* Disabled. Its first instruction, "mov dh, 17h" (B6 17), had its B6 replaced by a ret (C3), so
     * StartUp's call returns at once and the 17h and the rest, 1DC7-1E0B, are dead data (db).
     * Decoded, the routine was:
     *   print "<Insert Scenario Disk>" at row 23, column 8 (PrintAt, the string at 0C90h, inside
     *     FileCharsetUlt, no label);
     *   DiskCheckResult = DiskCheckStub();
     *   wait for a key (KeyReady, ReadKey); '1'-'4', 'a'-'d' or 'A'-'D' select drive 0-3 as the
     *     default drive (DOS 0Eh); any other key keeps the current one; ret.
     * So DiskCheckResult stays 0 and JourneyOnward's "(Strange Disk)" cannot happen. */
}

/* asm: AskNumber @1E0C ignore: CursorCol -- GetCursor/SetCursor stand for the word access */
u16 AskNumber(void)
{
    /* Read a number of up to two digits at the cursor (ReadNumber); on a bad entry beep (sound
     * 0FEh), blank the two places and ask again. Returns AL = the number in BCD, AH = in binary. */
    u16 dx = GetCursor();                       /* mov dx, word ptr CursorCol */
    for (;;) {                                  /* AskNumber_Retry */
        u16 ax = ReadNumber();
        if ((ax >> 8) != 0xFF) return ax;       /* AH = 0FFh: a hex digit was typed */
        Sound(0xFE);                            /* SndBeep (it saves DX) */
        SetCursor(dx);
        PutChar(0x20);
        PutChar(0x20);
        SetCursor(dx);
    }
}

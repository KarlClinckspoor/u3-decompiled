/* create.c: register, terminate, create a character, and the helpers of the whole program,
 * src/bootup/CREATE.ASM (194B-1E34).
 *
 * The roster commands of the party menu: ExamineRegister (list the 20 slots), TerminateChar and
 * CreateChar (with DrawCreateForm, EnterCharacter and ShowPointsLeft: name, sex, race, type and
 * 50 points for the four attributes). Then the helpers used by the whole program: WaitSpace,
 * PartyToRoster / RosterToParty (copy records between the party and the roster), RosterRecord,
 * AnimateDemo (for the title), CheckAlive and AnyAlive, AskNumber, and AskScenarioDisk, disabled
 * by a patched ret. (The chain load of EXODUS.BIN is JourneyOnward, title.c.) A roster number is
 * asked as "Entry#" and must be 1-20 ("(1-20 Only!)").
 *
 * Character record (64 bytes, docs/FORMATS.md): +00 name (NUL-ended, at most 9 letters here),
 * +10h in-party flag (0FFh), +11h status letter, +12h..+15h strength, dexterity, intelligence,
 * wisdom (BCD), +16h race, +17h class, +18h sex (letters), +1Ah hit points, +1Ch maximum hit
 * points, +21h food, +23h gold (BCD words), +28h armour worn, +29h the count of armour kind 1
 * (Cloth), +30h weapon readied, +31h the count of weapon kind 1 (Dagger).
 *
 * Pushes/pops of registers and flags are not written.
 */

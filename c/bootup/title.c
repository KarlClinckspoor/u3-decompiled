/* asm: TitleLoop_Prompt @12C8
 * Step: a cell number of 0FFh is a pause of `value` rounds; else the cell becomes value/2 and, when that
 * is a tile of 8 or more, one round follows; tiles below 8 are set without a pause. A round is six times
 * AnimateDemo (animate the tiles, redraw the block). StartUp enters here (after drawing the frame itself). */
void TitleLoop_Prompt(void)
{
    PrintAt(AT(0x17, 0x0C), MsgPressSpace);     /* "Press <Space>" in the bottom line of the frame */
    for (;;) {
        u16 si = DemoStep[0] | (DemoStep[1] << 8);      /* DemoStep is a word (inc word ptr DemoStep) */
        si++;                                   /* starts at 1FFh, so the first step is 0 */
        if (si == 0x200) si = 0;
        DemoStep[0] = si & 0xFF;
        DemoStep[1] = si >> 8;
        u16 bx = MovesCells[si];                /* bh = 0 */
        u8 al = MovesValues[si];
        u8 ah;
        if (bx == 0xFF) {
            ah = al;                            /* a pause of AL rounds */
        } else {
            al >>= 1;
            DemoTiles[bx] = al;
            if (al < 8) continue;               /* jb TitleLoop_Step: no pause for a tile below 8 */
            ah = 1;
        }
        do {                                    /* TitleLoop_Round */
            AnimateDemo();
            AnimateDemo();
            AnimateDemo();
            AnimateDemo();
            AnimateDemo();
            AnimateDemo();
            ah--;                               /* BUG, as in the original: a pause of 0 rounds counts down from
                                                   0 to 0FFh and takes 256 rounds (dec ah / jne) */
        } while (ah != 0);
        if (!KeyReady()) continue;              /* je TitleLoop_Step: no key */
        ReadKey();                              /* the key itself is dropped */
        RunMainMenu();
        TitleLoop();                            /* jmp TitleLoop: again from the top (never returns) */
        return;                                 /* only the C unwinding */
    }
}

/* asm: DrawMenuFrame @132B
 * Draw the frame of the menu area in colour 2 (magenta, 2222h): top line at text row 10 (columns 1-38),
 * left and right columns 0 and 39 (rows 10-23) and a bottom line at screen offset DX (always 1CC0h,
 * row 23). The other possible bottom line (1CC0h or 1E00h, row 24) is cleared first. */
void DrawMenuFrame(u16 dx)
{
    u16 bx = 0x1E00;
    bx ^= 0x1CC0;
    bx ^= dx;                                   /* BX = 1E00h if DX = 1CC0h, else 1CC0h */
    for (u16 cx = 0x28; cx != 0; cx--) {        /* 40 cells */
        FillCell(0, bx);
        bx += 2;
    }
    bx = dx;
    for (u16 cx = 0x28; cx != 0; cx--) {        /* the bottom line: pixels 0 2 0 2 ...: a dotted magenta line */
        FillCell(0x2222, bx);
        bx += 2;
    }
    bx = 0x0C82;                                /* row 10, column 1 */
    for (u16 cx = 0x26; cx != 0; cx--) {
        FillCell(0x2222, bx);
        bx += 2;
    }
    bx = 0x0C80;                                /* row 10, column 0 */
    for (u16 cx = 0x0E; cx != 0; cx--) {
        FillCell(0x2222, bx);
        bx += 0x140;                            /* next text row */
    }
    bx = 0x0CCE;                                /* row 10, column 39 */
    for (u16 cx = 0x0E; cx != 0; cx--) {
        FillCell(0x2222, bx);
        bx += 0x140;
    }
}


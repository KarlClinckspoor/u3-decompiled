/* asm: RunMainMenu @13A0
 * The main menu ("From the depths of hell...", Option: Return to the View, Organize a Party,
 * Journey Onward). The choice is made with AskChoice (choose a key of a list, show its name,
 * confirm with Enter). J: JourneyOnward (returns only on an error); O: the party menu; R or Esc:
 * back to the title. */
void RunMainMenu(void)
{
    for (;;) {                                  /* RunMainMenu_Redraw */
        ClearMenu();
        DrawMenuFrame(0x1CC0);
        PrintAt(AT(0x15, 0x03), MsgCopyright);
        PrintAt(AT(0x16, 0x0D), MsgLordBritish);
        PrintAt(AT(0x0B, 0x07), MsgFromDepths);
        PrintAt(AT(0x0C, 0x07), MsgVengeance);
        PrintAt(AT(0x0F, 0x10), MsgOptionSpace);
        PrintAt(AT(0x11, 0x0B), MsgMenuReturn);
        PrintAt(AT(0x12, 0x0C), MsgMenuOrganize);
        PrintAt(AT(0x13, 0x0D), MsgMenuJourney);
        SwapCursor(AT(0x0F, 0x17));
        u8 al = AskChoice(4, MainMenuKeys, MainMenu);   /* 4 keys: R O J Esc */
        if (al == 0x4A) {                       /* 'J' */
            JourneyOnward();
            continue;
        }
        if (al == 0x4F) {                       /* 'O' */
            RunOrganizeMenu();
            continue;
        }
        return;                                 /* R or Esc */
    }
}

/* asm: JourneyOnward @1437
 * Start the game. Refuses with "(No Party)" when no party is formed, "(Strange Disk)" when
 * DiskCheckResult is 0FFh (never: see AskScenarioDisk) and "(No Active Players)" when none of the four
 * party records is Good or Poisoned. Otherwise chain-loads EXODUS.BIN (docs/HANDOFF.md): open it with
 * the PSP's FCB, record size = file size, plant at PSP:00FA "int 21h" (CD 21) followed by
 * "jmp word ptr [1328h]" (FF 26 28 13) and jump there with AH = 14h and SP = 00FA: DOS reads the
 * whole file to 0100, over this program, and the jmp goes through EXODUS's entry vector at 1328.
 * The open is not checked. */
void JourneyOnward(void)
{
    if (PartySize == 0) {                       /* party size */
        ClearMenu();
        PrintAt(AT(0x15, 0x0F), MsgNoParty);
        WaitSpace();
        return;
    }
    if (DiskCheckResult[0] == 0xFF) {                   /* the first of its 3 bytes */
        ClearMenu();
        PrintAt(AT(0x15, 0x0B), MsgStrangeDisk);
        WaitSpace();
        return;
    }
    if (AnyAlive() == 0) {                      /* AH = 0: none of the four records is Good or Poisoned */
        ClearMenu();
        PrintAt(AT(0x15, 0x09), MsgNoActivePlayers);
        WaitSpace();
        return;
    }
    DosSetDta((u8 *)(uintptr_t)0x100);          /* DOS 1Ah: DTA = 0100, this program's own start */
    DosParseName(FileExodusBin, PspFcb);        /* DOS 29h, AL = 0: "EXODUS.BIN" into the FCB at PSP:005C */
    DosOpenFcb(PspFcb);                         /* DOS 0Fh: open the FCB (the result is not checked) */
    FcbRecSize = FcbFileSize;                   /* the file size as the record size */
    ChainInt21 = 0x21CD;                        /* CD 21: int 21h */
    ChainJmp = 0x26FF;                          /* FF 26: jmp word ptr [...] */
    ChainJmpAddr = 0x1328;                      /* ... [1328h]: EXODUS's entry vector */
    FcbCurBlock = 0;
    FcbCurRec = 0;
    /* mov ah, 14h / lea sp, ChainInt21 / jmp sp: SP and IP = 00FAh, i.e. the planted code runs: */
    DosReadFcb(PspFcb);                         /* int 21h with AH = 14h: sequential read of the whole file to 0100,
                                                   over this program (the result is not checked) */
    EnterExodus();                              /* jmp word ptr [1328h]; never returns */
}

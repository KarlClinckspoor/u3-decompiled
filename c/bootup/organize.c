static u16 Rd(const u8 *p) { return p[0] | (p[1] << 8); }      /* mov ax, word ptr [p] */

/* The letter AL looked up in the key string at DI (CX letters) with `repne scasb`, as LookAtChar
 * does it: the index of the first match; a letter not found gives the last index (CX runs out). */
static unsigned FindKey(u8 al, const u8 *di, u16 cx)
{
    u16 si = cx;
    bool found;
    do {
        found = (*di++ == al);
        cx--;
    } while (cx != 0 && !found);
    return si - cx - 1;                         /* sub si, cx / dec si */
}

/* asm: RunOrganizeMenu @14C9
 * The "Party Organization" menu, chosen with AskChoice (key, name, Enter); runs the chosen
 * command and shows the menu again, until M, Q or Esc. */
void RunOrganizeMenu(void)
{
    for (;;) {                                  /* RunOrganize_Redraw */
        ClearMenu();
        DrawMenuFrame(0x1CC0);
        PrintAt(AT(0x0B, 0x0B), MsgPartyOrganization);
        PrintAt(AT(0x0D, 0x10), MsgOption);
        PrintAt(AT(0x0F, 0x0A), MsgMenuExamine);
        PrintAt(AT(0x10, 0x0B), MsgMenuCreate);
        PrintAt(AT(0x11, 0x0D), MsgMenuForm);
        PrintAt(AT(0x12, 0x0B), MsgMenuDisperse);
        PrintAt(AT(0x13, 0x0A), MsgMenuTerminate);
        PrintAt(AT(0x14, 0x0B), MsgMenuLook);
        PrintAt(AT(0x15, 0x0F), MsgMenuMain);
        SwapCursor(AT(0x0D, 0x17));
        u8 al = AskChoice(9, OrganizeKeys, OrganizeMenu);   /* 9 keys: E C F D T M Q L Esc */
        if (al == 0x45) ExamineRegister();      /* 'E' */
        else if (al == 0x43) CreateChar();      /* 'C' */
        else if (al == 0x46) FormParty();       /* 'F' */
        else if (al == 0x44) DisperseParty();   /* 'D' */
        else if (al == 0x54) TerminateChar();   /* 'T' */
        else if (al == 0x4C) LookAtChar();      /* 'L' */
        else return;                            /* M, Q, Esc */
    }
}

/* asm: LookAtChar @158F
 * "Look at a Character": ask a roster number (1-20) and show the character: name, sex, race, type
 * (class), status, weapon, armour on the left; strength, dexterity, intelligence, wisdom, hit
 * points, experience, food and gold on the right. For a member of the party the party's copy
 * (PartyChars) is shown, not the roster's. The letters are turned into names by finding them in
 * the key strings (a letter not found gives the last name). */
void LookAtChar(void)
{
    ClearMenu();
    PrintAt(AT(0x0F, 0x0A), MsgLookTitle);
    PrintAt(AT(0x12, 0x10), MsgEntry);
    u16 ax = AskNumber();                       /* AL = BCD, AH = binary */
    u8 al = ax & 0xFF;
    u8 ah = ax >> 8;
    if (ah == 0 || ah > 0x14) {                 /* LookAtChar_BadNum */
        PrintAt(AT(0x15, 0x0E), MsgOnly1To20);
        WaitSpace();
        return;
    }
    u8 dl = al;                                 /* the BCD number, kept for the title line */
    u8 *bx = RosterRecord(ah);                  /* mov bl, ah */
    if (bx[0] == 0) {                           /* empty slot? LookAtChar_NoOne */
        PrintAt(AT(0x15, 0x0D), MsgNoOneThere);
        WaitSpace();
        return;
    }
    ClearMenu();
    al = dl;
    PrintAt(AT(0x0B, 0x0F), MsgEntry);          /* "Entry#" and the number */
    PrintBcdByte(al);
    if (bx[0x10] == 0xFF) {                     /* in the party? */
        /* find the roster number (AH, binary) among the four members: BL = its place (0-3) */
        unsigned place = FindKey(ah, PartyRosterNums, 4);
        bx = PartyChars + 0x40 * place;         /* the party's record */
    }
    /* LookAtChar_Fields */
    PrintAt(AT(0x0D, 0x03), MsgNameColon);
    PrintStr(bx);                               /* +00 name */
    PrintAt(AT(0x0E, 0x03), MsgSexColon);
    PrintStr(SexNames[FindKey(bx[0x18], SexKeys, 3)]);          /* sex */
    PrintAt(AT(0x0F, 0x03), MsgRaceColon);
    PrintStr(RaceNames[FindKey(bx[0x16], RaceKeys, 5)]);        /* race */
    PrintAt(AT(0x10, 0x03), MsgTypeColon);
    PrintStr(ClassNames[FindKey(bx[0x17], ClassKeys, 0x0B)]);   /* class */
    PrintAt(AT(0x11, 0x01), MsgStatusColon);
    PrintStr(StatusNames[FindKey(bx[0x11], StatusKeys, 4)]);    /* status */
    PrintAt(AT(0x13, 0x01), MsgWeaponColon);
    PrintStr(WeaponNames[bx[0x30]]);            /* weapon readied (no range check) */
    PrintAt(AT(0x14, 0x01), MsgArmourColon);
    PrintStr(ArmourNames[bx[0x28]]);            /* armour worn (no range check) */
    PrintAt(AT(0x0D, 0x1B), MsgStrengthColon);
    PrintBcdByte(bx[0x12]);                     /* strength */
    PrintAt(AT(0x0E, 0x1A), MsgDexterityColon);
    PrintBcdByte(bx[0x13]);                     /* dexterity */
    PrintAt(AT(0x0F, 0x17), MsgIntelligenceColon);
    PrintBcdByte(bx[0x14]);                     /* intelligence */
    PrintAt(AT(0x10, 0x1D), MsgWisdomColon);
    PrintBcdByte(bx[0x15]);                     /* wisdom */
    PrintAt(AT(0x12, 0x17), MsgHitPointsColon);
    PrintBcdWord(Rd(bx + 0x1A));                /* hit points */
    PrintAt(AT(0x13, 0x17), MsgExperienceColon);
    PrintBcdWord(Rd(bx + 0x1E));                /* experience */
    PrintAt(AT(0x14, 0x1D), MsgFoodColon);
    PrintBcdWord(Rd(bx + 0x21));                /* food */
    PrintAt(AT(0x15, 0x1D), MsgGoldColon);
    PrintBcdWord(Rd(bx + 0x23));                /* gold */
    WaitSpace();                                /* LookAtChar_Done */
}

/* asm: FormParty @1792
 * "Form the Party": refused with "(Party in Use)" while a party exists. Asks up to four roster
 * numbers ("Player-1" ... "Player-4"); 0 ends the list early. A number above 20, an empty slot
 * ("(No one there)") or one already chosen ("Already Selected") cancels everything chosen so far
 * (ReleaseParty). Then the party is set up on foot (tile 3Fh) on Sosaria (location 0) at x 2Ch,
 * y 14h, the members' records copied in, and PARTY.ULT and ROSTER.ULT saved: "(Formed)".
 * Note (as in the original): the "(No Active Players)" test (AnyAlive) runs before the records are
 * copied, on the old party records (zero after a Disperse), and refuses when one of them is
 * alive: looks reversed or misplaced; a party of dead characters can be formed (JourneyOnward
 * refuses it).
 * Note: the roster number is stored in PartyRosterNums before it is checked, so a rejected
 * number stays at index PartySize (ReleaseParty, which counts down from PartySize - 1, does not
 * clear it). */
void FormParty(void)
{
    ClearMenu();
    PrintAt(AT(0x0D, 0x0D), MsgFormTitle);
    if (PartySize != 0) {                       /* a party exists */
        PrintAt(AT(0x10, 0x0D), MsgPartyInUse); /* "(Party in Use)" */
        WaitSpace();                            /* FormParty_Done */
        return;
    }
    for (u16 cx = 4; cx != 0; cx--) {           /* "Player-4-" ... "Player-1-" on rows 13h ... 10h */
        PrintAt(AT(cx + 0x0F, 0x0F), MsgPlayerDash);
        PrintDigit(cx);
        PutChar(0x2D);                          /* '-' */
    }
    bool no_one = false, taken = false;
    for (;;) {                                  /* FormParty_Ask */
        SwapCursor(AT(PartySize + 0x10, 0x18)); /* after "Player-n-" */
        u16 ax = AskNumber();                   /* AL = BCD, AH = binary */
        u8 al = ax & 0xFF;
        u8 ah = ax >> 8;
        if (ah > 0x14) { no_one = true; break; }
        if (al == 0) break;                     /* FormParty_Finish: 0 ends the list */
        PartyRosterNums[PartySize] = ah;        /* the member's roster number */
        u8 *bx = RosterRecord(ah);              /* mov bl, ah */
        if (bx[0] == 0) { no_one = true; break; }
        if (bx[0x10] == 0xFF) { taken = true; break; }      /* +10h: already in the party */
        bx[0x10] = 0xFF;
        PartySize++;
        if (PartySize >= 4) break;              /* cmp PartySize, 4 / jb FormParty_Ask */
    }
    if (!no_one && !taken) {                    /* FormParty_Finish */
        if (PartySize == 0) no_one = true;
        else if (AnyAlive() == 0xFF) {          /* AnyAlive, on the OLD party records (see the note above) */
            PrintAt(AT(0x15, 0x09), MsgNoActivePlayers);    /* "(No Active Players)" */
            ReleaseParty();
            WaitSpace();                        /* FormParty_Done */
            return;
        } else {
            Location = 0;                       /* Sosaria */
            PartyBuf[0] = 0x3F;                 /* the party's tile: on foot */
            PartyX = 0x2C;                      /* x 44 */
            PartyY = 0x14;                      /* y 20 */
            RosterToParty();
            SaveFile(PartyBuf, 0x112, FilePartyUlt);    /* save CX bytes at BX as the file named at DX */
            SaveFile(Roster, 0x500, FileRosterUlt);
            Location = 1;                       /* back to 1 for the library (KeyReady) */
            PrintAt(AT(0x15, 0x10), MsgFormed);
            WaitSpace();                        /* FormParty_Done */
            return;
        }
    }
    if (no_one) {                               /* FormParty_NoOne */
        PrintAt(AT(0x15, 0x0D), MsgNoOneThere);
        ReleaseParty();
    } else {                                    /* FormParty_Taken */
        PrintAt(AT(0x15, 0x0D), MsgAlreadySelected);
        ReleaseParty();
    }
    WaitSpace();                                /* FormParty_Done */
}

/* asm: ReleaseParty @18AF
 * Undo the party: for each member, last first, clear its roster number in PartyRosterNums and its
 * roster record's party flag (+10h); the party size ends at 0. */
void ReleaseParty(void)
{
    if (PartySize == 0) return;
    do {                                        /* ReleaseParty_Loop */
        u8 bl = PartySize;
        u8 al = PartyRosterNums[bl - 1];
        PartyRosterNums[bl - 1] = 0;
        u8 *bx = RosterRecord(al);              /* mov bl, al */
        bx[0x10] = 0;
        PartySize--;
    } while (PartySize != 0);                   /* dec byte ptr PartySize / jne */
}

/* asm: DisperseParty @18DF
 * "Disperse the Party": copy the party's records back to the roster (PartyToRoster), release the
 * members, clear the four party records and save PARTY.ULT and ROSTER.ULT: "(Dispersed!)".
 * "(No Party)" when there is none. */
void DisperseParty(void)
{
    ClearMenu();
    PrintAt(AT(0x11, 0x0B), MsgDisperseTitle);
    if (PartySize == 0) {                       /* DisperseParty_NoParty */
        PrintAt(AT(0x14, 0x0F), MsgNoParty);
        WaitSpace();                            /* DisperseParty_Done */
        return;
    }
    PartyToRoster();
    ReleaseParty();
    for (u16 cx = 0x100; cx != 0; cx--)         /* rep stosb: the four records */
        PartyChars[0x100 - cx] = 0;
    SaveFile(PartyBuf, 0x112, FilePartyUlt);
    SaveFile(Roster, 0x500, FileRosterUlt);
    PrintAt(AT(0x13, 0x0E), MsgDispersed);
    WaitSpace();                                /* DisperseParty_Done */
}

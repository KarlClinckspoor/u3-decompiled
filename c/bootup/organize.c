/* organize.c: the party menu: look, form, disperse, src/bootup/ORGANIZE.ASM (14C9-194B).
 *
 * RunOrganizeMenu is the "Party Organization" menu: Examine the Register, Create a Character,
 * Terminate a Character (create.c), Form the Party (FormParty), Disperse the Party
 * (DisperseParty), Look at a Character (LookAtChar), Main Menu. The party lives in PartyBuf
 * (PARTY.ULT: an 18-byte header, then four 64-byte records, PartyChars); its header holds the
 * party size (PartySize) and the roster numbers (1-20) of the members (PartyRosterNums). A roster
 * record (Roster, ROSTER.ULT, 20 x 40h) whose +10h flag is 0FFh is in the party; while the party
 * exists its up-to-date copy is the party record, written back at Disperse. Forming and
 * dispersing save both files.
 *
 * Character record offsets used here (docs/FORMATS.md): +00 name, +10h in-party flag, +11h status
 * letter, +12h..+15h strength, dexterity, intelligence, wisdom (BCD), +16h race, +17h class,
 * +18h sex (letters), +1Ah hit points (BCD word), +1Eh experience (BCD word), +21h food (BCD
 * word), +23h gold (BCD word), +28h armour worn, +30h weapon readied.
 *
 * Pushes/pops of registers and flags are not written.
 */
